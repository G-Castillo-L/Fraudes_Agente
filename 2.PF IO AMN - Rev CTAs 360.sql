WITH
CTA_SOL AS (
  SELECT DISTINCT 
    CTA_CVE, BR_SOLIC_CVE 
  FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CTA` 
  INNER JOIN CTAS USING (CTA_CVE)
)
SELECT
    BR_SOLIC_CVE AS SOLICITUD,
    B.CTA_CVE AS CUENTA,
    SAFE_CAST(BR_EMP_PRM AS NUMERIC) AS EMPLEADO1,
    BR_EMP_CVE AS EMPLEADO2,
    SAFE_CAST(BR_TDA_ADM AS NUMERIC) AS TDA_ADMIN,
    SAFE_CAST(BR_TDA_CAP AS NUMERIC) AS TDA_CAPTURA,
    CONCAT(
      TRIM(COALESCE(BR_NOM, "")), " ",
      TRIM(COALESCE(BR_APE_PAT, "")), " ",
      TRIM(COALESCE(BR_APE_MAT, ""))
    ) AS NOMBRE,
    TRIM(BR_EMBOSADO) AS NOM_EMBOSADO,
    TRIM(BR_RFC) AS RFC,
    TRIM(BR_CURP) AS CURP,
    TRIM(CAST(BR_EDAD AS STRING)) AS EDAD,
    TRIM(UPPER(BR_MAIL)) AS EMAIL,
    SAFE_CAST(
      SUBSTR(
        CONCAT(
          COALESCE(ZEROS_TO_NULL(CAST(BR_LADA AS STRING)), ""),
          COALESCE(ZEROS_TO_NULL(CAST(BR_TEL AS STRING)), "")
        ),
        -10
      ) AS NUMERIC
    ) AS TEL,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(BR_CEL AS STRING)), -10) AS NUMERIC) AS CEL,
    CONCAT(
      TRIM(COALESCE(BR_DIR, "")), ", ",
      TRIM(COALESCE(BR_COL, "")), ", ",
      COALESCE(CAST(BR_CDP AS STRING), ""), ", ",
      TRIM(COALESCE(BR_CIU, "")), ", ",
      TRIM(COALESCE(BR_EDO, "")), ", ",
      TRIM(COALESCE(BR_PAIS, ""))
    ) AS DIRECCION,
    TRIM(BR_SEXO) AS SEXO,
    BR_FCH_APE AS FCH_APERTURA,
    TRIM(BR_NOM_CONY) AS NOM_CONYUG,
    BR_FCH_NAC_CONY AS FCH_NAC_CONYUG,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(BR_CEL_CONY AS STRING)), -10) AS NUMERIC) AS CEL_CONYUG,
    TRIM(BR_EMPR_CONY) AS EMP_CONYUG,
    TRIM(BR_EMPR) AS EMPLEO,
    CONCAT(
      TRIM(COALESCE(BR_DIR_EMPR, "")), ", ",
      TRIM(COALESCE(BR_COL_EMPR, "")), ", ",
      TRIM(COALESCE(BR_CDP_EMPR, "")), ", ",
      TRIM(COALESCE(BR_EDO_EMPR, ""))
    ) AS DIR_EMPLEO,
    SAFE_CAST(
      SUBSTR(
        CONCAT(
          COALESCE(ZEROS_TO_NULL(CAST(BR_LADA_OFI AS STRING)), ""),
          COALESCE(ZEROS_TO_NULL(CAST(BR_TEL_OFI AS STRING)), "")
        ),
        -10
      ) AS NUMERIC
    ) AS TEL_OFI,
    TRIM(BR_REF1) AS NOM_REF1,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(BR_TEL_REF1 AS STRING)), -10) AS NUMERIC) AS TEL_REF1,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(BR_CEL_REF1 AS STRING)), -10) AS NUMERIC) AS CEL_REF1,
    TRIM(BR_REF2) AS NOM_REF2,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(BR_TEL_REF2 AS STRING)), -10) AS NUMERIC) AS TEL_REF2,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(BR_CEL_REF2 AS STRING)), -10) AS NUMERIC) AS CEL_REF2
  FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VFAC_APIA` AS A
  INNER JOIN CTA_SOL AS B
    USING(BR_SOLIC_CVE) 
  ORDER BY BR_FCH_APE DESC;

