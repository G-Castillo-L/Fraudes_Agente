WITH BONIF AS (
  SELECT
    SAFE_CAST(ARU.CTA_CVE AS NUMERIC) AS CTA_CVE, TXN_IMP AS IMP, 
    ARU.TXN_USR AS ID_VPL, VPL.USR AS USR, VPL.EMP_NOM AS EMP_NOM, 
    ARU.TXN_DES AS DESCRIP, ARU.TXN_TDA, ARU.PLAN_CVE,
    ARU.TXN_FCH AS FECHA_TXN, TXN_TDA AS TDA
  FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_ARU080_DETALLE_TXN` AS ARU
  LEFT JOIN USR_VPL AS VPL
    ON ARU.TXN_USR = VPL.ID_VPL
    AND VPL.FCH_ALT <= ARU.TXN_FCH
    AND (VPL.FCH_BAJ IS NULL OR VPL.FCH_BAJ > ARU.TXN_FCH)
  WHERE TXN_CDO IN UNNEST(TXN_BON)
    AND SAFE_CAST(ARU.CTA_CVE AS NUMERIC) IN (SELECT CTA_CVE FROM CTAS)
    AND ARU.TXN_ANIO >= EXTRACT(YEAR FROM FE_INI)
)
SELECT *
FROM BONIF
ORDER BY FECHA_TXN;

