CREATE TEMP TABLE CTA_TRJ_BASE AS (
  SELECT DISTINCT
    SAFE_CAST(CTA_CVE AS NUMERIC) AS CTA_CVE,
    SAFE_CAST(TRJ_NUM AS NUMERIC) AS TRJ_NUM,
    SAFE_CAST(CTE_CVE_UNICO AS NUMERIC) AS CTE_CVE,
    TRJ_EDO_CVE,
    IND_TIT
  FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CTA_TRJ`
  WHERE SAFE_CAST(CTA_CVE AS NUMERIC) IN (SELECT CTA_CVE FROM CTAS)
);

CREATE TEMP TABLE USR_VPL AS (
  SELECT
    EMP_NOM, CVE_EMP, USR, ID_USER AS ID_VPL, NOM_PERF, TDA, TDA_NOM, FCH_ALT, FCH_BAJ
  FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VDIM_PREVFRAU_USR_VPL_HIST`
);

CREATE TEMP TABLE VPL_INFO AS (
  WITH 
  SDO_AUX AS (
    SELECT
      A.CTA_CVE, 
      STRING_AGG(
        CONCAT(
          B.TRJ_NUM, 
          " | EDO: ",
          TRJ_EDO_CVE,
          " | TIT: ",
          IND_TIT)
        , "\n") AS TRJ_NUM,
      CTA_FCH_SOL, CTA_EDO_CVE, SAFE_CAST(BR_SOLIC_CVE AS NUMERIC) AS BR_SOLIC_CVE, CTA_NIV_MOR,
      CONCAT(CCR_CVE_BLQ_UNO, RAZON_BLQ_UNO_CVE) AS  BLQ1, CONCAT(CCR_CVE_BLQ_DOS, RAZON_BLQ_DOS_CVE) AS BLQ2,
      CTA_IMP_LIM_CRD, CTA_SDO_ACT, CTA_HIST_PAGOS
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VFAC_SDO_CTA_MES` AS A
    INNER JOIN CTA_TRJ_BASE AS B
      USING(CTA_CVE)
    WHERE ANIO = EXTRACT(YEAR FROM CURRENT_DATE()) AND MES = EXTRACT(MONTH FROM CURRENT_DATE())
    GROUP BY 
      CTA_CVE, CTA_FCH_SOL, CTA_EDO_CVE, BR_SOLIC_CVE, CTA_NIV_MOR,
      CCR_CVE_BLQ_UNO, RAZON_BLQ_UNO_CVE, CCR_CVE_BLQ_DOS, RAZON_BLQ_DOS_CVE,
      CTA_IMP_LIM_CRD, CTA_SDO_ACT, CTA_HIST_PAGOS
  ),
  CLIE_FTES AS (
    SELECT DISTINCT
      CTA_CUSTOMER AS CTE_UNI,
      CTA_CVE,
      CONCAT(
        TRIM(COALESCE(CTE_NOM, "")), " ",
        TRIM(COALESCE(CTE_APE_PAT, "")), " ",
        TRIM(COALESCE(CTE_APE_MAT, ""))
      ) AS NOMBRE,
      TRIM(CTE_CVE_RFC) AS RFC,
      TRIM(UPPER(CTE_EMA)) AS EMAIL,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL AS STRING)), -10) AS NUMERIC) AS TEL,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_CEL AS STRING)), -10) AS NUMERIC) AS CEL,
      CONCAT(
        TRIM(COALESCE(CTE_DES_DIR_UNO, "")), ", ",
        TRIM(COALESCE(CTE_DES_DIR_DOS, "")), ", ",
        COALESCE(CAST(CDP_CVE AS STRING), ""), ", ",
        TRIM(COALESCE(CTE_DES_CIU, ""))
      ) AS DIRECCION,
      SEX_CVE AS SEXO,
      CTE_FCH_NAC AS FCH_NAC,
      CTE_FCH_ALT AS FCH_APERTURA,
      TRIM(CTE_EMPR) AS EMPLEO,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL_OFI AS STRING)), -10) AS NUMERIC) AS TEL_OFI,
      TRIM(CTE_CONYUGE) AS NOM_CONYUGE,
      TRIM(CTE_NOM_REFERENCIA1) AS NOM_REF1,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL_REFERENCIA1 AS STRING)), -10) AS NUMERIC) AS TEL_REF1,
      TRIM(CTE_NOM_REFERENCIA2) AS NOM_REF2,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL_REFERENCIA2 AS STRING)), -10) AS NUMERIC) AS TEL_REF2
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CLIE_FTES_VPL`
    WHERE CTA_CVE IN (SELECT CTA_CVE FROM CTAS)
  )
  SELECT 
    A.*, B.* EXCEPT(CTA_CVE)
  FROM CLIE_FTES AS A
  LEFT JOIN SDO_AUX AS B
    USING (CTA_CVE)
);

SELECT *
FROM VPL_INFO
ORDER BY CTE_UNI, CTA_CVE, FCH_APERTURA;

