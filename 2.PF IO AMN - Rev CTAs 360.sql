-- ACLA
-- ============================================================
WITH CTA_TRJ AS (
  SELECT DISTINCT
    CTA_CVE, TRJ_NUM, CTE_CVE
  FROM CTA_TRJ_BASE
),
ACLA AS (
  SELECT DISTINCT 
    B.CTA_CVE, NUM_TARJETA, NOMBRE_CLIENTE, FOLIO AS FOLIO_ACLARACION, 
    DATE(FCH_HORA_ACLARACION) AS FCH_ACLA, TIME(FCH_HORA_ACLARACION) AS HRA_ACLA,
    TIPO_ACLARACION_INICIAL,
    DATE(FCH_HORA_DICTAMEN) AS FCH_DICTAMEN, TIME(FCH_HORA_DICTAMEN) AS HRA_DICTAMEN,
    TIPO_ACLARACION_FINAL,
    USUARIO_DICTAMEN,
    DOCUMENTO, OBSERVACION, HECHOS
  FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_FOLIO_ACLARACIONES` AS A
  INNER JOIN CTA_TRJ AS B ON SAFE_CAST(NUM_TARJETA AS NUMERIC) = TRJ_NUM
  WHERE DATE(FCH_HORA_ACLARACION) >= FE_INI
),
ACLA_TXN AS (
  SELECT 
    A.FOLIO_ACLARACION, SUM(MONTO) AS MONTO,
    STRING_AGG(
      CONCAT(
        'FolTxn: ', COALESCE(CAST(FOLIO_TRANSACCION AS STRING), ''),
        ' | Ref23: ', COALESCE(CAST(REFERENCIA23 AS STRING), ''),
        ' | Aut: ', COALESCE(CAST(AUTORIZACION AS STRING), ''),
        ' | FchTxn: ', COALESCE(CAST(DATE(FCH_HORA_TRANSACCION) AS STRING), ''),
        ' | HraTxn: ', COALESCE(CAST(TIME(FCH_HORA_TRANSACCION) AS STRING), ''),
        ' | Tda: ', COALESCE(CAST(TIENDA AS STRING), ''),
        ' | Imp: ', COALESCE(CAST(MONTO AS STRING), ''),
        ' | Term: ', COALESCE(CAST(TERMINAL AS STRING), ''),
        ' | Bol: ', COALESCE(CAST(BOLETA AS STRING), ''),
        ' | Plan: ', COALESCE(CAST(PLAN AS STRING), ''),
        ' | ModEnt: ', COALESCE(CAST(MODOENTRADA AS STRING), ''),
        ' | CVV2: ', COALESCE(CAST(PRESENCIACVV2 AS STRING), ''),
        ' | MetAut: ', COALESCE(CAST(METODO_AUTENTICACION AS STRING), ''),
        ' | NipOn: ', COALESCE(CAST(NIP_ON_US AS STRING), ''),
        ' | NipOff: ', COALESCE(CAST(NIP_OFF_US AS STRING), ''),
        ' | DicTxn: ', COALESCE(CAST(DICTAMEN_TRANSACCION AS STRING), ''),
        ' | FrauTrn: ', COALESCE(CAST(TIPO_FRAUDE_TRN AS STRING), ''),
        ' | ObsTrn: ', COALESCE(CAST(OBSERVACIONES_TRN AS STRING), ''),
        ' | ObsGen: ', COALESCE(CAST(OBSERVACIONES_GENERAL AS STRING), '')
      ),
      '\n' ORDER BY FOLIO_TRANSACCION
    ) AS TXN_AGRUPADAS
  FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_TRN_ACLARACIONES` AS A
  INNER JOIN ACLA AS B USING(FOLIO_ACLARACION)
  GROUP BY A.FOLIO_ACLARACION
)
SELECT 
  ACLA.*,
  ACLA_TXN.MONTO, 
  ACLA_TXN.TXN_AGRUPADAS
FROM ACLA
LEFT JOIN ACLA_TXN USING(FOLIO_ACLARACION)
ORDER BY FCH_ACLA;

