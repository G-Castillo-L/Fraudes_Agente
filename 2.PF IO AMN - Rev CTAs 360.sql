-- R02
-- ============================================================
WITH R02_MATCH AS (
  SELECT DISTINCT
    CTE_CVE, CTA_CVE, TRJ_NUM, CTA_CVE AS MATCH_VAL, 'CTA_CVE' AS TYPE_MATCH
  FROM CTA_TRJ_BASE
  WHERE CTA_CVE IS NOT NULL

  UNION DISTINCT

  SELECT DISTINCT
    CTE_CVE, CTA_CVE, TRJ_NUM, TRJ_NUM AS MATCH_VAL, 'TRJ_NUM' AS TYPE_MATCH
  FROM CTA_TRJ_BASE
  WHERE TRJ_NUM IS NOT NULL

  UNION DISTINCT

  SELECT DISTINCT
    CTE_CVE, CTA_CVE, TRJ_NUM, CTE_CVE AS MATCH_VAL, 'CTE_CVE' AS TYPE_MATCH
  FROM CTA_TRJ_BASE
  WHERE CTE_CVE IS NOT NULL
),
R02 AS (
  SELECT DISTINCT
    M.CTE_CVE, M.CTA_CVE,
    CONCAT(M.TYPE_MATCH, " - ", CAST(M.MATCH_VAL AS STRING)) AS MATCH_KEY,
    R02.MANT_FCH, R02.MANT_HRA, R02.MANT_CDO, R02.MANT_DES,
    R02.DAT_A, R02.DAT_N, 
    R02.VPL_USR, VPL.ID_VPL AS ID, VPL.EMP_NOM AS EMP_NOM, VPL.NOM_PERF, VPL.TDA,
    VPL.FCH_ALT, VPL.FCH_BAJ
  FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_R02_MOVIMIENTOS_VPL` AS R02
  INNER JOIN R02_MATCH AS M
    ON SAFE_CAST(R02.CTA_CVE AS NUMERIC) = M.MATCH_VAL
  LEFT JOIN USR_VPL AS VPL
    ON R02.VPL_USR = VPL.USR
    AND VPL.FCH_ALT <= R02.MANT_FCH
    AND (VPL.FCH_BAJ IS NULL OR VPL.FCH_BAJ > R02.MANT_FCH)
  WHERE R02.MANT_FCH >= FE_INI
)
SELECT *
FROM R02
ORDER BY DATETIME(MANT_FCH, MANT_HRA)
;

