-- ============================================================
-- HELPERS
-- ============================================================
CREATE TEMP FUNCTION ZEROS_TO_NULL(s STRING) AS (
  CASE
    WHEN s IS NULL THEN NULL
    WHEN TRIM(s) = "" THEN NULL
    WHEN REGEXP_CONTAINS(TRIM(s), r"^0+$") THEN NULL
    ELSE TRIM(s)
  END
);

CREATE TEMP FUNCTION NORM_NAME(s STRING) AS (
  NULLIF(TRIM(UPPER(s)), "")
);

CREATE TEMP FUNCTION NORM_EMAIL(s STRING) AS (
  NULLIF(TRIM(LOWER(s)), "")
);


