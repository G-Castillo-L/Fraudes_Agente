-- ============================================================
-- R09
-- ============================================================
WITH R02_CATALOGO AS (
  SELECT DISTINCT
    SAFE_CAST(MANT_CDO AS NUMERIC) AS MANT_CDO, TRIM(MANT_DES) AS MANT_DES
  FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_R02_MOVIMIENTOS_VPL`
),
R09_MATCH AS (
  SELECT DISTINCT
    CTA_CVE AS MATCH_VAL, 'CTA_CVE' AS TYPE_MATCH
  FROM CTA_TRJ_BASE
  WHERE CTA_CVE IS NOT NULL

  UNION DISTINCT

  SELECT DISTINCT
   TRJ_NUM AS MATCH_VAL, 'TRJ_NUM' AS TYPE_MATCH
  FROM CTA_TRJ_BASE
  WHERE TRJ_NUM IS NOT NULL

  UNION DISTINCT

  SELECT DISTINCT
    CTE_CVE AS MATCH_VAL, 'CTE_CVE' AS TYPE_MATCH
  FROM CTA_TRJ_BASE
  WHERE CTE_CVE IS NOT NULL
),
R09 AS (
  SELECT DISTINCT
    M.MATCH_VAL,
    CONCAT(M.TYPE_MATCH, " - ", CAST(M.MATCH_VAL AS STRING)) AS MATCH_KEY,
    R09.FCH, R09.HRA, SAFE_CAST(R09.CDE_OCC AS NUMERIC) AS MANT_CDO, TRIM(R09.DES) AS MANT_DES,
    TRIM(R09.DAT_A) AS DAT_A, TRIM(R09.DAT_N) AS DAT_N, TRIM(R09.USR) AS USR,
    VPL.ID_VPL AS ID, VPL.NOM_PERF, VPL.TDA, VPL.TDA_NOM, VPL.FCH_ALT, VPL.FCH_BAJ
  FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_R09` AS R09
  INNER JOIN R09_MATCH AS M
    ON SAFE_CAST(CONCAT(SAFE_CAST(SAFE_CAST(R09.CTE_CVE AS NUMERIC) AS STRING), IFNULL(LPAD(SAFE_CAST(SAFE_CAST(FLG1 AS INT64) AS STRING), 2, '0'), "")) AS NUMERIC) = M.MATCH_VAL
  LEFT JOIN R02_CATALOGO AS R02X
    ON SAFE_CAST(R09.CDE_OCC AS NUMERIC) = R02X.MANT_CDO
    AND TRIM(R09.DES) = R02X.MANT_DES
  LEFT JOIN USR_VPL AS VPL
    ON TRIM(R09.USR) = VPL.USR
    AND VPL.FCH_ALT <= R09.FCH
    AND (VPL.FCH_BAJ IS NULL OR VPL.FCH_BAJ > R09.FCH)
  WHERE R09.FCH >= FE_INI
    AND R02X.MANT_CDO IS NULL
)
SELECT *
FROM R09
ORDER BY DATETIME(FCH, HRA)
;

