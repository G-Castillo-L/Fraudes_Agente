DECLARE MTH_BCKWARD INT64 DEFAULT 12;

CREATE TEMP TABLE CTAS_REV AS (
  SELECT CAST(x AS NUMERIC) AS CTA_CVE
  FROM UNNEST([
    '1400000031181724'


  ]) AS x
);  
CREATE TEMP TABLE RNG_FCH_CTA AS (
  SELECT
    CTA_CVE,
    DATE_TRUNC(DATE_SUB(MAX(TRN_FCH_EFE), INTERVAL MTH_BCKWARD MONTH), MONTH) AS FCH_MIN,
    MAX(TRN_FCH_EFE) AS FCH_MAX
  FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VFAC_TRN_CRD`
  INNER JOIN CTAS_REV USING(CTA_CVE)
  GROUP BY CTA_CVE
);
CREATE TEMP TABLE DATOS_VDIM_CTA_TRJ AS (
  SELECT DISTINCT CTA_CVE, TRJ_NUM
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CTA_TRJ`
    INNER JOIN CTAS_REV USING (CTA_CVE)
);
