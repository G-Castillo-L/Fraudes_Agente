            AND A.IDC_REF_CROPPED_FACE IS NULL
            AND A.IDC_REF_ORI_BACK IS NULL
            AND A.IDC_REF_ORI_FRONT IS NULL
            AND A.IDC_REF_CAP_BACK IS NOT NULL
            AND A.SIGNATURE IS NULL
            AND A.PID_READABILITY_CHK IS NULL
          ) THEN 'DESERTION'
          WHEN A.SD_CONFIG_NOM IN (
            'SBB_SEL', 'LIVERPOOL_INE', 'SBB_SEL_MIN', 'LIV_SEL_JUSTME_TV_INE'
          )
          AND A.FCH_VALIDACION < DATE '2024-05-24'
          AND A.SD_SCORE_VAL_STT IN ('MANUAL_FAIL', 'UNKNOWN', 'FAIL') THEN 'FAIL'
          WHEN A.SD_CONFIG_NOM IN (
            'SBB_SEL', 'LIVERPOOL_INE', 'SBB_SEL_MIN', 'LIV_SEL_JUSTME_TV_INE'
          )
          AND A.FCH_VALIDACION < DATE '2024-05-24'
          AND A.SD_SCORE_VAL_STT IN ('MANUAL_OK', 'MANUAL', 'OK') THEN 'OK'
          WHEN A.SD_CONFIG_NOM IN (
            'SBB_SEL', 'LIVERPOOL_INE', 'SBB_SEL_MIN', 'LIV_SEL_JUSTME_TV_INE'
          )
          AND A.FCH_VALIDACION < DATE '2024-05-24'
          AND A.SD_SCORE_VAL_STT IN ('WARN') THEN 'WARN'
          WHEN A.SD_CONFIG_NOM IN (
            'SBB_SEL', 'LIVERPOOL_INE', 'SBB_SEL_MIN', 'LIV_SEL_JUSTME_TV_INE'
          )
          AND A.FCH_VALIDACION >= DATE '2024-05-24'
          AND A.SD_SCORE_VAL_STT IN ('MANUAL_OK', 'MANUAL', 'OK') THEN 'OK'
          WHEN A.SD_CONFIG_NOM IN (
            'SBB_SEL', 'LIVERPOOL_INE', 'SBB_SEL_MIN', 'LIV_SEL_JUSTME_TV_INE'
          )
          AND A.FCH_VALIDACION >= DATE '2024-05-24'
          AND A.SD_SCORE_VAL_STT IN ('WARN') THEN 'WARN'
          WHEN A.SD_CONFIG_NOM IN (
            'SBB_SEL', 'LIVERPOOL_INE', 'SBB_SEL_MIN', 'LIV_SEL_JUSTME_TV_INE'
          )
          AND A.FCH_VALIDACION >= DATE '2024-05-24'
          AND A.SD_SCORE_VAL_STT NOT IN ('MANUAL_OK', 'MANUAL', 'OK', 'WARN')
          AND (
            A.PID_INC_SCORE_STT IN ('FAIL')
            OR A.PID_IDVALIDATION_OVERAL_STT IN ('FAIL')
            OR A.FR_STT IN ('FAIL')
            OR A.FC_OVERALL_STT IN ('FAIL')
            OR A.FC_LIV_SCORE_STT IN ('FAIL')
            OR A.CWL_SCORE < 0
            OR (
              A.RK_ORIG_STT IN ('FAILED')
              AND (A.CWL_SCORE IS NULL OR A.CWL_SCORE < 0)
            )
          ) THEN 'FAIL'
          WHEN A.SD_CONFIG_NOM IN (
            'SBB_SEL', 'LIVERPOOL_INE', 'SBB_SEL_MIN', 'LIV_SEL_JUSTME_TV_INE'
          )
          AND A.FCH_VALIDACION >= DATE '2024-05-24'
          AND A.SD_SCORE_VAL_STT NOT IN ('MANUAL_OK', 'MANUAL', 'OK', 'WARN')
          AND (
            A.PID_INC_SCORE_STT NOT IN ('FAIL')
            AND A.PID_IDVALIDATION_OVERAL_STT NOT IN ('FAIL')
            AND A.FR_STT NOT IN ('FAIL')
            AND A.FC_OVERALL_STT NOT IN ('FAIL')
            AND A.FC_LIV_SCORE_STT NOT IN ('FAIL')
            AND (
              A.RK_ORIG_STT NOT IN ('FAILED')
              OR (A.RK_ORIG_STT IN ('FAILED') AND A.CWL_SCORE >= 0)
            )
          ) THEN 'OK'
          ELSE 'REVISAR'
        END
      WHEN A.FLUJO_SESION = 'TAB' THEN
        CASE
          WHEN A.CATEGO_TAB IN ('DESERTION') THEN 'DESERTION'
          WHEN A.CATEGO_TAB IN ('OK', 'WARN') THEN 'OK'
          WHEN A.CATEGO_TAB NOT IN ('DESERTION', 'OK', 'WARN')
            AND A.FC_ATTEMPTS IS NULL
            AND A.PID_INC_SCORE_STT = 'FAIL' THEN 'MODULO ID'
          WHEN A.CATEGO_TAB NOT IN ('DESERTION', 'OK', 'WARN')
            AND A.FC_ATTEMPTS IS NULL
            AND A.PID_INC_SCORE_STT IN ('OK', 'WARN') THEN 'OK SIN SELFIE'
          WHEN A.CATEGO_TAB NOT IN ('DESERTION', 'OK', 'WARN')
            AND A.FC_ATTEMPTS IS NOT NULL
            AND A.PID_INC_SCORE_STT IN ('OK', 'WARN')
            AND A.SD_CONFIG_NOM NOT IN ('LIV_TAB_INE', 'SBB_TAB_INE', 'SBB_TAB_MIN_INE', 'LIV_TAB_BYD_INE')
            AND A.FR_STT = 'OK'
