    IDC_DIR AS DIRECCION,
    SD_CONFIG_NOM,
    SD_SCORE_VAL_STT,
    SD_SCORE_VAL,
    IDC_REF_CROPPED_BACK,
    IDC_REF_CROPPED_FRONT,
    IDC_REF_CROPPED_FACE,
