-- ============================================================
-- HELPERS
-- ============================================================
CREATE TEMP FUNCTION ZEROS_TO_NULL(s STRING) AS (
  CASE
    WHEN s IS NULL THEN NULL
    WHEN TRIM(s) = "" THEN NULL
    WHEN REGEXP_CONTAINS(TRIM(s), r"^0+$") THEN NULL
    ELSE TRIM(s)
  END
);
CREATE TEMP FUNCTION NORM_NAME(s STRING) AS (
  NULLIF(TRIM(UPPER(s)), "")
);
CREATE TEMP FUNCTION NORM_EMAIL(s STRING) AS (
  NULLIF(TRIM(LOWER(s)), "")
);
CREATE TEMP FUNCTION NORM_DEVICE(s STRING) AS (
  NULLIF(TRIM(LOWER(s)), "")
);

-- ============================================================
-- INPUT TABLES
-- ============================================================
CREATE TEMP TABLE INPUT_NOMBRES AS
SELECT DISTINCT NORM_NAME(x) AS NOMBRE
FROM UNNEST(Q_NOMBRES) x
WHERE NORM_NAME(x) IS NOT NULL;

CREATE TEMP TABLE INPUT_EMAILS AS
SELECT DISTINCT NORM_EMAIL(x) AS EMAIL
FROM UNNEST(Q_EMAILS) x
WHERE NORM_EMAIL(x) IS NOT NULL;

CREATE TEMP TABLE INPUT_CELS AS
SELECT DISTINCT x AS CEL
FROM UNNEST(Q_CELS) x
WHERE x IS NOT NULL;

CREATE TEMP TABLE INPUT_DEVICE_IDS AS
SELECT DISTINCT NORM_DEVICE(x) AS DEVICE_ID
FROM UNNEST(Q_DEVICE_IDS) x
WHERE NORM_DEVICE(x) IS NOT NULL;


