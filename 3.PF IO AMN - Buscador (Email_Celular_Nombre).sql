WITH
BASE AS (
  SELECT
    CTA_CUSTOMER AS CTE_UNI,
    CTA_CVE AS CUENTA,
    CONCAT(
      TRIM(COALESCE(CTE_NOM, "")), " ",
      TRIM(COALESCE(CTE_APE_PAT, "")), " ",
      TRIM(COALESCE(CTE_APE_MAT, ""))
    ) AS NOMBRE,
    TRIM(CTE_CVE_RFC) AS RFC,
    TRIM(UPPER(CTE_EMA)) AS EMAIL,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL AS STRING)), -10) AS NUMERIC) AS TEL,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_CEL AS STRING)), -10) AS NUMERIC) AS CEL,
    CONCAT(
      TRIM(COALESCE(CTE_DES_DIR_UNO, "")), ", ",
      TRIM(COALESCE(CTE_DES_DIR_DOS, "")), ", ",
      COALESCE(CAST(CDP_CVE AS STRING), ""), ", ",
      TRIM(COALESCE(CTE_DES_CIU, ""))
    ) AS DIRECCION,
    SEX_CVE AS SEXO,
    CTE_FCH_NAC AS FCH_NAC,
    CTE_FCH_ALT AS FCH_APERTURA,
    TRIM(CTE_EMPR) AS EMPLEO,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL_OFI AS STRING)), -10) AS NUMERIC) AS TEL_OFI,
    TRIM(CTE_CONYUGE) AS NOM_CONYUGE,
    TRIM(CTE_NOM_REFERENCIA1) AS NOM_REF1,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL_REFERENCIA1 AS STRING)), -10) AS NUMERIC) AS TEL_REF1,
    TRIM(CTE_NOM_REFERENCIA2) AS NOM_REF2,
    SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL_REFERENCIA2 AS STRING)), -10) AS NUMERIC) AS TEL_REF2
  FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CLIE_FTES_VPL`
),
J AS (
  SELECT
    B.*,
    IF(C.CEL IS NOT NULL, 1, 0) AS __hit_cel,
    IF(E.EMAIL IS NOT NULL, 1, 0) AS __hit_email,
    IF(N.NOMBRE IS NOT NULL, 1, 0) AS __hit_nombre,
    CASE
      WHEN C.CEL IS NOT NULL THEN 1
      WHEN E.EMAIL IS NOT NULL THEN 2
      WHEN N.NOMBRE IS NOT NULL THEN 3
      ELSE 9
    END AS __match_pri
  FROM BASE B
  LEFT JOIN INPUT_CELS C
    ON SAFE_CAST(B.CEL AS INT64) = C.CEL
  LEFT JOIN INPUT_EMAILS E
    ON NORM_EMAIL(B.EMAIL) = E.EMAIL
  LEFT JOIN INPUT_NOMBRES N
    ON NORM_NAME(B.NOMBRE) LIKE CONCAT("%", N.NOMBRE, "%")
  WHERE C.CEL IS NOT NULL OR E.EMAIL IS NOT NULL OR N.NOMBRE IS NOT NULL
)
SELECT
  CASE
    WHEN __hit_cel = 1 THEN "CELULAR"
    WHEN __hit_email = 1 THEN "EMAIL"
    WHEN __hit_nombre = 1 THEN "NOMBRE"
    ELSE NULL
  END AS MATCH_TYPE,
  CTE_UNI, CUENTA,
  NOMBRE, RFC,
  EMAIL, TEL, CEL, DIRECCION, SEXO, FCH_NAC,
  FCH_APERTURA,
  NOM_CONYUGE,
  EMPLEO, TEL_OFI,
  NOM_REF1, TEL_REF1,
  NOM_REF2, TEL_REF2
FROM J
QUALIFY
  ROW_NUMBER() OVER(
    PARTITION BY CAST(CTE_UNI AS STRING), CAST(CUENTA AS STRING)
    ORDER BY __match_pri
  ) = 1;

