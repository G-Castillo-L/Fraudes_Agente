    PID_IDVALIDATION_OVERAL_STT,
    FR_STT,
    FC_ATTEMPTS,
    FC_OVERALL_STT,
    FC_LIV_SCORE_STT,
    CWL_SCORE,
    RK_ORIG_STT,
    GOV_STT,
    GOV_OVERALL_STT,
    DF_ID,
    DF_TYPE -- <--- NUEVO CAMPO AGREGADO
  FROM `crp-pro-dwh-semanticagold.EIL_DP_VMASTER.VFAC_PREVFRAU_VAL_INCODE`
),
AUX AS (
  SELECT
    B.*,
    CASE
      WHEN B.SD_CONFIG_NOM IN (
        'SBB_SEL', 'LIVERPOOL_INE', 'SBB_SEL_MIN', 'LIV_SEL_JUSTME_TV_INE'
      )
      THEN 'SEL'
      WHEN B.SD_CONFIG_NOM IN (
        'LIV_TAB_INE', 'LIV_TAB_PAS', 'SBB_TAB_INE', 'SBB_TAB_PAS',
        'SBB_TAB_MIN_INE', 'SBB_TAB_MIN_PAS', 'LIV_TAB_BYD_INE', 'LIV_TAB_BYD_PAS'
      ) THEN 'TAB'
