      A.AUT_BEFORE_OK, A.AUT_AFTER_OK,
      A.AUT_BEFORE_CNT, A.AUT_BEFORE_OK_CNT,
      A.AUT_AFTER_CNT, A.AUT_AFTER_OK_CNT,
      A.AUT_BEFORE_PATH, A.AUT_AFTER_PATH,
      IF(
        E.ENR_BEFORE.TS_ENR IS NOT NULL
        OR E.ENR_AFTER.TS_ENR IS NOT NULL
        OR A.AUT_BEFORE.TS_AUT IS NOT NULL
        OR A.AUT_AFTER.TS_AUT IS NOT NULL,
        1,
        0
      ) AS FLG_BIO_REALIZADO
    FROM ENR_MET AS E
    LEFT JOIN ENR_HIST_MET AS H
      ON E.ID_ROW = H.ID_ROW
      AND E.TYPE = H.TYPE
      AND E.SRC = H.SRC
      AND E.KEY_VAL = H.KEY_VAL
      AND SAFE_CAST(E.DOB6 AS STRING) = SAFE_CAST(H.DOB6 AS STRING)
    LEFT JOIN AUT_MET AS A
      ON E.ID_ROW = A.ID_ROW
      AND E.TYPE = A.TYPE
      AND E.SRC = A.SRC
      AND E.KEY_VAL = A.KEY_VAL
      AND SAFE_CAST(E.DOB6 AS STRING) = SAFE_CAST(A.DOB6 AS STRING)
    LEFT JOIN (
      SELECT DISTINCT ID_ROW, BLOQ2
      FROM BIO_OP
    ) AS O
      ON E.ID_ROW = O.ID_ROW
  ),  
  KEY_STATUS AS (
    SELECT
      *,
      CASE
        WHEN FLG_BIO_REALIZADO = 0
          AND IFNULL(HAS_ENR_HIST_ANY, FALSE)
        THEN 'NO AUTENTICARON HUELLA (TENIA ENROLAMIENTO)'

        WHEN FLG_BIO_REALIZADO = 0
        THEN 'SIN REGISTRO'

        WHEN ENR_BEFORE_OK.TS_ENR IS NOT NULL
        THEN 'BIOMETRICO OK'

        WHEN AUT_BEFORE_OK.TS_AUT IS NOT NULL
        THEN 'BIOMETRICO OK'

        WHEN AUT_AFTER_OK.TS_AUT IS NOT NULL
          AND ENR_AFTER_OK.TS_ENR IS NOT NULL
          AND ENR_AFTER_OK.TS_ENR > AUT_AFTER_OK.TS_AUT
          AND NOT REGEXP_CONTAINS(IFNULL(BLOQ2, ''), r'F#')
        THEN 'REENROLA (EXITOSO)'

        WHEN AUT_AFTER_OK.TS_AUT IS NOT NULL
          AND ENR_AFTER_OK.TS_ENR IS NOT NULL
          AND ENR_AFTER_OK.TS_ENR > AUT_AFTER_OK.TS_AUT
          AND REGEXP_CONTAINS(IFNULL(BLOQ2, ''), r'F#')
        THEN 'REENROLA (NO EXITOSO)'

        WHEN AUT_AFTER_OK.TS_AUT IS NOT NULL
        THEN 'AUTENTICA DESPUES DEL EVENTO (EXITOSO)'

        WHEN ENR_AFTER_OK.TS_ENR IS NOT NULL
        THEN 'ENROLA DESPUES DEL EVENTO (EXITOSO)'

        WHEN ENR_BEFORE.TS_ENR IS NOT NULL
        THEN 'REGISTRO FALLIDO'

        WHEN AUT_BEFORE.TS_AUT IS NOT NULL
        THEN 'AUTENTICACION FALLIDA'

        WHEN AUT_AFTER.TS_AUT IS NOT NULL
          AND ENR_AFTER.TS_ENR IS NOT NULL
          AND ENR_AFTER.TS_ENR > AUT_AFTER.TS_AUT
          AND REGEXP_CONTAINS(IFNULL(BLOQ2, ''), r'F#')
        THEN 'REENROLA (NO EXITOSO)'

        WHEN AUT_AFTER.TS_AUT IS NOT NULL
        THEN 'AUTENTICA DESPUES DEL EVENTO (FALLIDO)'

        WHEN ENR_AFTER.TS_ENR IS NOT NULL
        THEN 'ENROLA DESPUES DEL EVENTO (FALLIDO)'

        ELSE 'SIN REGISTRO'
      END AS MATCH_BIO_STT,

      CASE
        WHEN FLG_BIO_REALIZADO = 0
          AND IFNULL(HAS_ENR_HIST_ANY, FALSE)
        THEN 10

        WHEN FLG_BIO_REALIZADO = 0
        THEN 11

        WHEN ENR_BEFORE_OK.TS_ENR IS NOT NULL
        THEN 1

        WHEN AUT_BEFORE_OK.TS_AUT IS NOT NULL
        THEN 1

        WHEN AUT_AFTER_OK.TS_AUT IS NOT NULL
          AND ENR_AFTER_OK.TS_ENR IS NOT NULL
          AND ENR_AFTER_OK.TS_ENR > AUT_AFTER_OK.TS_AUT
          AND NOT REGEXP_CONTAINS(IFNULL(BLOQ2, ''), r'F#')
        THEN 2

        WHEN AUT_AFTER_OK.TS_AUT IS NOT NULL
        THEN 3

        WHEN ENR_AFTER_OK.TS_ENR IS NOT NULL
        THEN 4

        WHEN ENR_BEFORE.TS_ENR IS NOT NULL
        THEN 5

        WHEN AUT_BEFORE.TS_AUT IS NOT NULL
        THEN 6

        WHEN AUT_AFTER.TS_AUT IS NOT NULL
          AND ENR_AFTER_OK.TS_ENR IS NOT NULL
          AND ENR_AFTER_OK.TS_ENR > AUT_AFTER.TS_AUT
          AND REGEXP_CONTAINS(IFNULL(BLOQ2, ''), r'F#')
        THEN 7

        WHEN AUT_AFTER.TS_AUT IS NOT NULL
        THEN 8

        WHEN ENR_AFTER.TS_ENR IS NOT NULL
        THEN 9

        ELSE 99
      END AS STT_ORD
    FROM KEY_STATUS_BASE
  ),
  BEST_PER_ROW AS (
    SELECT
      ID_ROW, FLG_BIO_REALIZADO, MATCH_BIO_STT, STT_ORD,
      TYPE, SRC, KEY_VAL, BLOQ2,

      ENR_BEFORE, AUT_BEFORE, ENR_BEFORE_OK, AUT_BEFORE_OK,
