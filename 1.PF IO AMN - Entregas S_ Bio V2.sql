-- SCORECARD MENSUAL
-- TOTAL / LIVERPOOL / SUBURBIA
-- ============================================================
CREATE TEMP TABLE SCORECARD_EJECUTIVO AS (
  WITH BASE_SCORECARD_UNI AS (
    SELECT
      CASE
        WHEN REGEXP_CONTAINS(CAST(TIP_INF_R AS STRING), r'^1') THEN 'LIVERPOOL'
        WHEN REGEXP_CONTAINS(CAST(TIP_INF_R AS STRING), r'^2') THEN 'SUBURBIA'
        ELSE 'OTROS'
      END AS SEGMENTO_EMISOR,
      FCH_REP,
      IFNULL(FLG_EMBO, 0) AS FLG_EMBO,
      IFNULL(FLG_BIO_REALIZADO, 0) AS FLG_BIO_REALIZADO,
      IFNULL(TRJ_BIO_EXITOSO, 0) AS TRJ_BIO_EXITOSO,
      COALESCE(MATCH_BIO_STT, 'SIN MATCH_BIO_STT') AS MATCH_BIO_STT
    FROM RESULT_FINAL
    WHERE EXTRACT(YEAR FROM FCH_REP) = 2026
  ),
  BASE_SCORECARD AS (
    SELECT
      'EL PUERTO DE LIVERPOOL' AS REPORTE,
      *
    FROM BASE_SCORECARD_UNI

    UNION ALL

    SELECT
      'LIVERPOOL' AS REPORTE,
      *
    FROM BASE_SCORECARD_UNI
    WHERE SEGMENTO_EMISOR = 'LIVERPOOL'

    UNION ALL

    SELECT
      'SUBURBIA' AS REPORTE,
      *
    FROM BASE_SCORECARD_UNI
    WHERE SEGMENTO_EMISOR = 'SUBURBIA'
  ),
  PERIODIZED AS (
    SELECT REPORTE, 'ENE 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 1
    UNION ALL
    SELECT REPORTE, 'FEB 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 2
    UNION ALL
    SELECT REPORTE, 'MAR 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 3
    UNION ALL
    SELECT REPORTE, 'ABR 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 4
    UNION ALL
    SELECT REPORTE, 'MAY 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 5
    UNION ALL
    SELECT REPORTE, 'JUN 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 6
    UNION ALL
    SELECT REPORTE, 'JUL 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 7
    UNION ALL
    SELECT REPORTE, 'AGO 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 8
    UNION ALL
    SELECT REPORTE, 'SEP 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 9
    UNION ALL
    SELECT REPORTE, 'OCT 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 10
    UNION ALL
    SELECT REPORTE, 'NOV 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 11
    UNION ALL
    SELECT REPORTE, 'DIC 26' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD WHERE EXTRACT(MONTH FROM FCH_REP) = 12
    UNION ALL
    SELECT REPORTE, '2026' AS PERIODO, * EXCEPT(REPORTE) FROM BASE_SCORECARD
  ),
  TOT AS (
    SELECT
      REPORTE, PERIODO,
      COUNT(*) AS REGISTROS
    FROM PERIODIZED
    GROUP BY REPORTE, PERIODO
  ),
  EMBO AS (
    SELECT
      REPORTE, PERIODO,
      COUNT(*) AS REGISTROS
    FROM PERIODIZED
    WHERE FLG_EMBO = 1
    GROUP BY REPORTE, PERIODO
  ),
  BIO1 AS (
    SELECT
      REPORTE, PERIODO,
      COUNT(*) AS REGISTROS
    FROM PERIODIZED
    WHERE FLG_EMBO = 1
      AND FLG_BIO_REALIZADO = 1
    GROUP BY REPORTE, PERIODO
  ),
  BIO0 AS (
    SELECT
      REPORTE, PERIODO,
      COUNT(*) AS REGISTROS
    FROM PERIODIZED
    WHERE FLG_EMBO = 1
      AND FLG_BIO_REALIZADO = 0
    GROUP BY REPORTE, PERIODO
  ),
  BIO1_OK AS (
    SELECT
      REPORTE, PERIODO,
      COUNT(*) AS REGISTROS
    FROM PERIODIZED
    WHERE FLG_EMBO = 1
      AND FLG_BIO_REALIZADO = 1
      AND TRJ_BIO_EXITOSO = 1
    GROUP BY REPORTE, PERIODO
  ),
  BIO1_FAIL AS (
    SELECT
      REPORTE, PERIODO,
      COUNT(*) AS REGISTROS
    FROM PERIODIZED
    WHERE FLG_EMBO = 1
      AND FLG_BIO_REALIZADO = 1
      AND TRJ_BIO_EXITOSO = 0
    GROUP BY REPORTE, PERIODO
  ),
  STT_BIO1_FAIL AS (
    SELECT
      REPORTE, PERIODO, MATCH_BIO_STT,
      COUNT(*) AS REGISTROS
    FROM PERIODIZED
    WHERE FLG_EMBO = 1
      AND FLG_BIO_REALIZADO = 1
      AND TRJ_BIO_EXITOSO = 0
    GROUP BY REPORTE, PERIODO, MATCH_BIO_STT
  ),
  STT_BIO1_FAIL_ORD AS (
    SELECT
      REPORTE, MATCH_BIO_STT,
      ROW_NUMBER() OVER (
        PARTITION BY REPORTE
        ORDER BY COUNT(*) DESC, MATCH_BIO_STT
      ) AS ORD_STT
    FROM BASE_SCORECARD
    WHERE FLG_EMBO = 1
      AND FLG_BIO_REALIZADO = 1
      AND TRJ_BIO_EXITOSO = 0
    GROUP BY REPORTE, MATCH_BIO_STT
  ),
  ROWS_FIXED AS (
    SELECT
      T.REPORTE,
      10 AS ORDEN,
      'Emisiones Totales' AS FILA,
      'VAL' AS TIPO,
      T.PERIODO,
      T.REGISTROS AS NUMERADOR,
      NULL AS DENOMINADOR
    FROM TOT AS T

    UNION ALL

    SELECT
      T.REPORTE,
      11 AS ORDEN,
      '  % Embozada' AS FILA,
      'PCT' AS TIPO,
      T.PERIODO,
      E.REGISTROS AS NUMERADOR,
      T.REGISTROS AS DENOMINADOR
    FROM TOT AS T
    LEFT JOIN EMBO AS E
      USING (REPORTE, PERIODO)

    UNION ALL

    SELECT
      T.REPORTE,
      12 AS ORDEN,
      '  % No Embozada' AS FILA,
      'PCT' AS TIPO,
      T.PERIODO,
      T.REGISTROS - IFNULL(E.REGISTROS, 0) AS NUMERADOR,
      T.REGISTROS AS DENOMINADOR
    FROM TOT AS T
    LEFT JOIN EMBO AS E
      USING (REPORTE, PERIODO)

    UNION ALL

    SELECT
      E.REPORTE,
      20 AS ORDEN,
      'Embozadas' AS FILA,
      'VAL' AS TIPO,
      E.PERIODO,
      E.REGISTROS AS NUMERADOR,
      NULL AS DENOMINADOR
    FROM EMBO AS E

    UNION ALL

    SELECT
      E.REPORTE,
      21 AS ORDEN,
      '  % Biométrico Realizado' AS FILA,
      'PCT' AS TIPO,
      E.PERIODO,
      B1.REGISTROS AS NUMERADOR,
      E.REGISTROS AS DENOMINADOR
    FROM EMBO AS E
    LEFT JOIN BIO1 AS B1
      USING (REPORTE, PERIODO)

    UNION ALL

    SELECT
      E.REPORTE,
      22 AS ORDEN,
      '  % Biométrico No Realizado' AS FILA,
      'PCT' AS TIPO,
      E.PERIODO,
      B0.REGISTROS AS NUMERADOR,
      E.REGISTROS AS DENOMINADOR
    FROM EMBO AS E
    LEFT JOIN BIO0 AS B0
      USING (REPORTE, PERIODO)

    UNION ALL

    SELECT
      B1.REPORTE,
      30 AS ORDEN,
      'Biométrico Realizado' AS FILA,
      'VAL' AS TIPO,
      B1.PERIODO,
      B1.REGISTROS AS NUMERADOR,
      NULL AS DENOMINADOR
    FROM BIO1 AS B1

    UNION ALL

    SELECT
      B1.REPORTE,
      31 AS ORDEN,
      '  % Exitoso' AS FILA,
      'PCT' AS TIPO,
      B1.PERIODO,
      B1O.REGISTROS AS NUMERADOR,
      B1.REGISTROS AS DENOMINADOR
    FROM BIO1 AS B1
    LEFT JOIN BIO1_OK AS B1O
      USING (REPORTE, PERIODO)

    UNION ALL

    SELECT
      B1.REPORTE,
      32 AS ORDEN,
      '  % Fallido' AS FILA,
      'PCT' AS TIPO,
      B1.PERIODO,
      B1F.REGISTROS AS NUMERADOR,
      B1.REGISTROS AS DENOMINADOR
    FROM BIO1 AS B1
    LEFT JOIN BIO1_FAIL AS B1F
      USING (REPORTE, PERIODO)

    UNION ALL

    SELECT
      B1F.REPORTE,
      40 AS ORDEN,
      'Biométrico Fallido' AS FILA,
      'VAL' AS TIPO,
      B1F.PERIODO,
      B1F.REGISTROS AS NUMERADOR,
      NULL AS DENOMINADOR
    FROM BIO1_FAIL AS B1F
  ),
  ROWS_BIO1_FAIL_STT AS (
    SELECT
      S.REPORTE,
      40 + O.ORD_STT AS ORDEN,
      CASE S.MATCH_BIO_STT
        WHEN 'REGISTRO FALLIDO' THEN '  % Registro Fallido'
        WHEN 'AUTENTICACION FALLIDA' THEN '  % Autenticación Fallida'
        WHEN 'AUTENTICA DESPUES DEL EVENTO (FALLIDO)' THEN '  % Autentica Después Del Evento (Fallido)'
        WHEN 'ENROLA DESPUES DEL EVENTO (FALLIDO)' THEN '  % Enrola Después Del Evento (Fallido)'
        WHEN 'REENROLA (NO EXITOSO)' THEN '  % Reenrola (No Exitoso)'
        ELSE CONCAT('  % ', INITCAP(LOWER(S.MATCH_BIO_STT)))
      END AS FILA,
      'PCT' AS TIPO,
      S.PERIODO,
      S.REGISTROS AS NUMERADOR,
      B1F.REGISTROS AS DENOMINADOR
    FROM STT_BIO1_FAIL AS S
    INNER JOIN BIO1_FAIL AS B1F
      USING (REPORTE, PERIODO)
    INNER JOIN STT_BIO1_FAIL_ORD AS O
      ON S.REPORTE = O.REPORTE
      AND S.MATCH_BIO_STT = O.MATCH_BIO_STT
  ),
  ROWS_ALL AS (
    SELECT * FROM ROWS_FIXED
    UNION ALL
    SELECT * FROM ROWS_BIO1_FAIL_STT
  ),
  RENDERED AS (
    SELECT
      REPORTE,
      ORDEN,
      FILA,
      PERIODO,
      CASE
        WHEN TIPO = 'VAL' THEN
          CASE
            WHEN NUMERADOR IS NULL THEN ''
            ELSE CAST(CAST(NUMERADOR AS INT64) AS STRING)
          END
        WHEN TIPO = 'PCT' THEN
          CASE
            WHEN DENOMINADOR IS NULL OR DENOMINADOR = 0 OR NUMERADOR IS NULL THEN ''
            ELSE FORMAT('%.2f%%', 100 * SAFE_DIVIDE(NUMERADOR, DENOMINADOR))
          END
        ELSE ''
      END AS DISPLAY_VAL
    FROM ROWS_ALL
  )
  SELECT
    REPORTE,
    ORDEN,
    FILA,

    COALESCE(MAX(IF(PERIODO = 'ENE 26', DISPLAY_VAL, NULL)), '') AS `ENE 26`,
    COALESCE(MAX(IF(PERIODO = 'FEB 26', DISPLAY_VAL, NULL)), '') AS `FEB 26`,
    COALESCE(MAX(IF(PERIODO = 'MAR 26', DISPLAY_VAL, NULL)), '') AS `MAR 26`,
    COALESCE(MAX(IF(PERIODO = 'ABR 26', DISPLAY_VAL, NULL)), '') AS `ABR 26`,
    COALESCE(MAX(IF(PERIODO = 'MAY 26', DISPLAY_VAL, NULL)), '') AS `MAY 26`,
    COALESCE(MAX(IF(PERIODO = 'JUN 26', DISPLAY_VAL, NULL)), '') AS `JUN 26`,
    COALESCE(MAX(IF(PERIODO = 'JUL 26', DISPLAY_VAL, NULL)), '') AS `JUL 26`,
