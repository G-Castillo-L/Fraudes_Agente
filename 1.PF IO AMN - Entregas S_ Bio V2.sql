    WHERE E.FCH_ENR BETWEEN FE_INI AND FE_FIN
  ),
  FIL AS (
    SELECT
      TS_ENR, KEY10, CURP18, NOM_N, DOB6,
      ENR_FLG, CURP_FLG, INE_FLG, IUB,
      CASE 
          WHEN ((UPPER(INE_FLG) LIKE '%VERIFICACION EXITOSA%' OR UPPER(INE_FLG) LIKE '%PENDIENTE%' OR UPPER(INE_FLG) LIKE '%INESPERADO%') AND ENR_FLG LIKE '%SRV000%') THEN 'EXITOSO'
          WHEN (UPPER(INE_FLG) LIKE '%VERIFICACION EXITOSA%' AND ENR_FLG NOT LIKE '%SRV000%') THEN 'FALLIDO - SIN RIESGO'
          WHEN UPPER(INE_FLG) LIKE '%HUELLA NO HIT%' THEN 'FALLIDO'
          WHEN UPPER(INE_FLG) LIKE 'NO COINCIDEN DATOS DE LA CREDENCIAL - [La identificacion no esta vigente]' THEN 'FALLIDO - SIN RIESGO'
          WHEN UPPER(INE_FLG) LIKE '%MINUCIA%' THEN 'FALLIDO - MINUCIAS'
          WHEN UPPER(INE_FLG) LIKE '%[La identificacion no esta vigente] [Nombre no coincide][Apellido Paterno no coincide][Apellido Materno no coincide]%' THEN 'FALLIDO'
          WHEN UPPER(INE_FLG) NOT LIKE '%HUELLA NO HIT%' AND INE_FLG IS NOT NULL THEN 'FALLIDO - RIESGO'
          WHEN (UPPER(CURP_FLG) LIKE '%EXITOSO%' AND ENR_FLG LIKE '%SRV000%' AND INE_FLG IS NULL) THEN 'EXITOSO'
        ELSE 'REV'
      END AS FLG_EXI_TIP,
      CASE 
          WHEN ((UPPER(INE_FLG) LIKE '%VERIFICACION EXITOSA%' OR UPPER(INE_FLG) LIKE'%PENDIENTE%' OR UPPER(INE_FLG) LIKE "%INESPERADO%") AND ENR_FLG LIKE '%SRV000%') THEN 'EXITOSO'
          WHEN (UPPER(INE_FLG) LIKE '%VERIFICACION EXITOSA%' AND ENR_FLG NOT LIKE '%SRV000%') THEN 'EXITOSO'
          WHEN UPPER(INE_FLG) LIKE '%HUELLA NO HIT%' THEN 'FALLIDO'
          WHEN UPPER(INE_FLG) LIKE 'NO COINCIDEN DATOS DE LA CREDENCIAL - [La identificacion no esta vigente]' THEN 'EXITOSO' 
          WHEN UPPER(INE_FLG) LIKE '%MINUCIA%' THEN 'FALLIDO'
          WHEN UPPER(INE_FLG) LIKE '%[La identificacion no esta vigente] [Nombre no coincide][Apellido Paterno no coincide][Apellido Materno no coincide]%' THEN 'FALLIDO'
          WHEN UPPER(INE_FLG) NOT LIKE '%HUELLA NO HIT%' AND INE_FLG IS NOT NULL THEN 'EXITOSO'
          WHEN (UPPER (CURP_FLG) LIKE '%EXITOSO%' AND ENR_FLG LIKE '%SRV000%' AND INE_FLG IS NULL) THEN 'EXITOSO'
        ELSE 'REV' 
      END AS FLG_EXI
    FROM PRE
    WHERE CURP18 IN (SELECT CURP18 FROM KEY_CURP)
       OR KEY10 IN (SELECT KEY10 FROM KEY_KEY10)
       OR STRUCT(NOM_N, DOB6) IN (SELECT AS STRUCT NOM_N, DOB6 FROM KEY_NAME_DOB)
  )
  SELECT
    TS_ENR, FLG_EXI, FLG_EXI_TIP, ENR_FLG, CURP_FLG, INE_FLG, IUB,
    CURP18 AS ENR_CURP18,
    'CURP' AS TYPE, CURP18 AS KEY_VAL, '' AS KEY_DOB6
  FROM FIL
  WHERE CURP18 IS NOT NULL

  UNION ALL
  SELECT
    TS_ENR, FLG_EXI, FLG_EXI_TIP, ENR_FLG, CURP_FLG, INE_FLG, IUB,
    CURP18 AS ENR_CURP18,
    'KEY10' AS TYPE, KEY10 AS KEY_VAL, '' AS KEY_DOB6
  FROM FIL
  WHERE KEY10 IS NOT NULL

  UNION ALL
  SELECT
    TS_ENR, FLG_EXI, FLG_EXI_TIP, ENR_FLG, CURP_FLG, INE_FLG, IUB,
    CURP18 AS ENR_CURP18,
    'NAME_DOB' AS TYPE, NOM_N AS KEY_VAL, DOB6 AS KEY_DOB6
  FROM FIL
  WHERE NOM_N IS NOT NULL
    AND DOB6 IS NOT NULL
);
