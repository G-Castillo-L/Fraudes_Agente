    INNER JOIN CURP_ENR_U AS U
      ON NORM_CURP18(A.BR_CURP) = U.CURP18
    WHERE TRUE
      AND NORM_CURP18(A.BR_CURP) IS NOT NULL
  ),
  APIA_SDO AS (
    SELECT
      A.CURP18,
      S.CTA_CVE, S.CTA_SDO_ACT, S.CTA_IMP_LIM_CRD, 
      SAFE_DIVIDE(S.CTA_SDO_ACT, NULLIF(S.CTA_IMP_LIM_CRD, 0)) AS PCT_USO,
      A.BR_SOLIC_CVE,
      A.BR_TIPO_3, A.TIP_INF,
      A.RFC_APIA
    FROM APIA_CURP AS A
    INNER JOIN `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VFAC_SDO_CTA_MES` AS S
      ON A.BR_SOLIC_CVE = S.BR_SOLIC_CVE
      AND A.BR_TIPO_3 = SUBSTR(SAFE_CAST(S.BR_TIPO AS STRING), 1, 3)
      AND A.TIP_INF = SAFE_CAST(S.TIP_INF AS STRING) 
    WHERE TRUE
      AND S.ANIO = CUR_ANIO
      AND S.MES = CUR_MES
  ),
  FICO_INV AS (
    SELECT DISTINCT
      NULLIF(SAFE_CAST(A.BR_SOLIC_CVE AS NUMERIC), 0) AS BR_SOLIC_CVE,
      TRIM(A.BR_RFC) AS FICO_RFC
    FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_REP_SOL_FICO` AS A
    INNER JOIN (
      SELECT DISTINCT BR_SOLIC_CVE
      FROM APIA_SDO
      WHERE BR_SOLIC_CVE IS NOT NULL
    ) AS U
      ON NULLIF(SAFE_CAST(A.BR_SOLIC_CVE AS NUMERIC), 0) = U.BR_SOLIC_CVE
  ),
  CLIE_FTES_CLEAN AS (
    SELECT DISTINCT
      A.CTA_CVE,

      CONCAT(
        TRIM(COALESCE(CTE_NOM, "")), " ",
        TRIM(COALESCE(CTE_APE_PAT, "")), " ",
        TRIM(COALESCE(CTE_APE_MAT, ""))
      ) AS NOMBRE,

      IF(REGEXP_CONTAINS(TRIM(CTE_CVE_RFC), r"^0+"), NULL, SUBSTR(TRIM(CTE_CVE_RFC), 1, 13)) AS CTE_CVE_RFC,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL AS STRING)), -10) AS NUMERIC) AS TEL,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_CEL AS STRING)), -10) AS NUMERIC) AS CEL,
      UPPER(TRIM(CTE_EMA)) AS EMAIL,
      SAFE_CAST(CDP_CVE AS STRING) AS CDP_CVE,
      SEX_CVE AS SEXO,
      CTE_FCH_NAC AS FCH_NAC,
      CTE_FCH_ALT AS FCH_APERTURA
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CLIE_FTES_VPL` AS A
    INNER JOIN (SELECT DISTINCT CTA_CVE FROM APIA_SDO) AS K
      ON A.CTA_CVE = K.CTA_CVE
  ),
  MATCH_INV_RAW AS (
    SELECT
      A.CURP18, B.CTE_CVE_UNICO, A.BR_SOLIC_CVE, A.CTA_CVE, A.PCT_USO, A.CTA_SDO_ACT, A.CTA_IMP_LIM_CRD,
      F.NOMBRE, F.CTE_CVE_RFC, FI.FICO_RFC, A.RFC_APIA, F.EMAIL, F.CEL, F.CDP_CVE, F.SEXO,
      F.FCH_NAC, F.FCH_APERTURA
    FROM APIA_SDO AS A
    LEFT JOIN CLIE_FTES_CLEAN AS F
      ON F.CTA_CVE = A.CTA_CVE
    LEFT JOIN FICO_INV AS FI
      ON FI.BR_SOLIC_CVE = A.BR_SOLIC_CVE
    LEFT JOIN (SELECT DISTINCT CTE_CVE_UNICO, CTA_CVE FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CTA_TRJ` INNER JOIN (SELECT DISTINCT CTA_CVE FROM UNIV) USING (CTA_CVE)) AS B
      ON A.CTA_CVE = B.CTA_CVE
  ),
  MATCH_INV_DEDUP AS (
    SELECT *
    FROM MATCH_INV_RAW
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY CURP18, CTA_CVE
      ORDER BY PCT_USO DESC, CTA_SDO_ACT DESC
    ) = 1
  ),
  BASE_CONTACTS AS (
    SELECT DISTINCT
      U.CTA_CVE,
      NULLIF(UPPER(TRIM(U.EMAIL)), '') AS EMAIL_CLEAN,
      U.CEL AS CEL_CLEAN
    FROM UNIV AS U
  ),
  MATCH_INV_CONTACTS AS (
    SELECT DISTINCT
      I.CTA_CVE,
      NULLIF(UPPER(TRIM(I.EMAIL)), '') AS EMAIL_CLEAN,
      I.CEL AS CEL_CLEAN
    FROM MATCH_INV_DEDUP AS I
  ),
  CONTACTS_EMAIL_TO_CHECK AS (
    SELECT DISTINCT EMAIL_CLEAN
    FROM (
      SELECT EMAIL_CLEAN FROM BASE_CONTACTS
      UNION DISTINCT
      SELECT EMAIL_CLEAN FROM MATCH_INV_CONTACTS
    )
    WHERE EMAIL_CLEAN IS NOT NULL
  ),
  CONTACTS_CEL_TO_CHECK AS (
    SELECT DISTINCT CEL_CLEAN
    FROM (
      SELECT CEL_CLEAN FROM BASE_CONTACTS
      UNION DISTINCT
      SELECT CEL_CLEAN FROM MATCH_INV_CONTACTS
    )
    WHERE CEL_CLEAN IS NOT NULL
  ),
  CLIE_FTES_EMAIL_RFC_GT1 AS (
    SELECT
      EMAIL_CLEAN,
      COUNT(DISTINCT CTE_CVE_RFC_CLEAN) AS CNT_RFC_DIST_X_EMAIL
    FROM (
      SELECT
        NULLIF(UPPER(TRIM(CTE_EMA)), '') AS EMAIL_CLEAN,
        NULLIF(
          UPPER(TRIM(
            IF(
              REGEXP_CONTAINS(TRIM(IFNULL(CTE_CVE_RFC, '')), r'^0+'),
              NULL,
              SUBSTR(TRIM(CTE_CVE_RFC), 1, 13)
            )
          )),
          ''
        ) AS CTE_CVE_RFC_CLEAN
      FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CLIE_FTES_VPL`
      WHERE NULLIF(UPPER(TRIM(CTE_EMA)), '') IN (
        SELECT EMAIL_CLEAN FROM CONTACTS_EMAIL_TO_CHECK
      )
    )
    WHERE EMAIL_CLEAN IS NOT NULL
      AND CTE_CVE_RFC_CLEAN IS NOT NULL
    GROUP BY EMAIL_CLEAN
    HAVING COUNT(DISTINCT CTE_CVE_RFC_CLEAN) > 1
  ),
  CLIE_FTES_CEL_RFC_GT1 AS (
    SELECT
      CEL_CLEAN,
      COUNT(DISTINCT CTE_CVE_RFC_CLEAN) AS CNT_RFC_DIST_X_CEL
    FROM (
      SELECT
        SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_CEL AS STRING)), -10) AS NUMERIC) AS CEL_CLEAN,
        NULLIF(
          UPPER(TRIM(
            IF(
              REGEXP_CONTAINS(TRIM(IFNULL(CTE_CVE_RFC, '')), r'^0+'),
              NULL,
              SUBSTR(TRIM(CTE_CVE_RFC), 1, 13)
            )
          )),
          ''
        ) AS CTE_CVE_RFC_CLEAN
      FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CLIE_FTES_VPL`
      WHERE SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_CEL AS STRING)), -10) AS NUMERIC) IN (
        SELECT CEL_CLEAN FROM CONTACTS_CEL_TO_CHECK
      )
    )
    WHERE CEL_CLEAN IS NOT NULL
      AND CTE_CVE_RFC_CLEAN IS NOT NULL
    GROUP BY CEL_CLEAN
    HAVING COUNT(DISTINCT CTE_CVE_RFC_CLEAN) > 1
  ),
  MATCH_INV_PER_BASE AS (
    SELECT DISTINCT
      COALESCE(C.CTA_CVE, B.CTA_CVE) AS BASE_CTA_CVE,
      COALESCE(C.CTA_ENR_CURP18, B.APIA_CURP) AS CURP18,

      NULLIF(COUNT(I.CTA_CVE), 0) AS CNT_CTA_INV,

      MAX(EI.CNT_RFC_DIST_X_EMAIL) AS MATCH_INV_CNT_RFC_DIST_X_EMAIL_GT1,
      MAX(CI.CNT_RFC_DIST_X_CEL) AS MATCH_INV_CNT_RFC_DIST_X_CEL_GT1,

      STRING_AGG(
        DISTINCT IF(
          I.CTA_CVE IS NULL,
          NULL,
          FORMAT(
            'CVE_UNI=%s | BR_SOL=%s | CTA=%s\nUSO=%.2f%% | SDO=%s | LIM=%s\nNOM=%s | RFC=%s\nEMAIL=%s | CEL=%s | CDP=%s',
            COALESCE(CAST(I.CTE_CVE_UNICO AS STRING), ''),
            COALESCE(CAST(I.BR_SOLIC_CVE AS STRING), ''),
            CAST(I.CTA_CVE AS STRING),
            100 * IFNULL(I.PCT_USO, 0),
            COALESCE(CAST(I.CTA_SDO_ACT AS STRING), ''),
            COALESCE(CAST(I.CTA_IMP_LIM_CRD AS STRING), ''),
            COALESCE(I.NOMBRE, ''),
            COALESCE(I.CTE_CVE_RFC, ''),
            COALESCE(I.EMAIL, ''),
            COALESCE(CAST(I.CEL AS STRING), ''),
            COALESCE(I.CDP_CVE, '')
          )
        ),
        '\n'
      ) AS MATCH_INV_LOG
    FROM (SELECT DISTINCT CTA_CVE, CTE_CVE_UNICO, APIA_CURP FROM UNIV) AS B
    LEFT JOIN (SELECT DISTINCT CTA_CVE, CTE_CVE_UNICO, CTA_ENR_CURP18 FROM BIO_CTA) AS C
      ON B.CTA_CVE = C.CTA_CVE
    LEFT JOIN MATCH_INV_DEDUP AS I
      ON I.CURP18 = COALESCE(C.CTA_ENR_CURP18, B.APIA_CURP)
      AND I.CTE_CVE_UNICO != COALESCE(C.CTE_CVE_UNICO, B.CTE_CVE_UNICO)

    LEFT JOIN CLIE_FTES_EMAIL_RFC_GT1 AS EI
      ON NULLIF(UPPER(TRIM(I.EMAIL)), '') = EI.EMAIL_CLEAN
    LEFT JOIN CLIE_FTES_CEL_RFC_GT1 AS CI
      ON I.CEL = CI.CEL_CLEAN

    WHERE TRUE
      AND COALESCE(C.CTA_ENR_CURP18, B.APIA_CURP) IS NOT NULL
      AND IS_CURP18(B.APIA_CURP)
      AND IS_CURP18(C.CTA_ENR_CURP18)
    GROUP BY BASE_CTA_CVE, CURP18
  )
  SELECT
    U.*,
    T.FLG_BIO_REALIZADO,
    T.TRJ_BIO_REALIZADO_LOG,

    T.TRJ_BIO_EXITOSO,
    T.MATCH_BIO_STT,

    T.TRJ_BIO_LOG,

    T.TRJ_BIO_AUT_FUERA_HORARIO AS AUT_OUT,
    T.TRJ_BIO_ENR_FUERA_HORARIO AS ENR_OUT,
    
    C.CTA_ENR_EXISTE,
    C.CTA_ENR_LOG,
    C.CTA_ENR_CURP18,

    M.CNT_CTA_INV,
    M.MATCH_INV_LOG,

    BE.CNT_RFC_DIST_X_EMAIL AS BASE_CNT_RFC_DIST_X_EMAIL_GT1,
    BC.CNT_RFC_DIST_X_CEL AS BASE_CNT_RFC_DIST_X_CEL_GT1,

    M.MATCH_INV_CNT_RFC_DIST_X_EMAIL_GT1,
    M.MATCH_INV_CNT_RFC_DIST_X_CEL_GT1
  FROM UNIV AS U
  LEFT JOIN BIO_TRJ AS T
    ON T.ID_ROW = CONCAT(CAST(U.CTA_CVE AS STRING), '|', CAST(U.TRJ_NUM AS STRING))
  LEFT JOIN BIO_CTA AS C
    ON C.CTA_CVE = U.CTA_CVE
  LEFT JOIN MATCH_INV_PER_BASE AS M
    ON M.CURP18 = C.CTA_ENR_CURP18
    AND M.BASE_CTA_CVE = U.CTA_CVE
  LEFT JOIN CLIE_FTES_EMAIL_RFC_GT1 AS BE
    ON NULLIF(UPPER(TRIM(U.EMAIL)), '') = BE.EMAIL_CLEAN
  LEFT JOIN CLIE_FTES_CEL_RFC_GT1 AS BC
    ON U.CEL = BC.CEL_CLEAN
);

