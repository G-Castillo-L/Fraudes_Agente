    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY ID_ROW
      ORDER BY
        STT_ORD,
        CASE SRC
          WHEN 'FICO_RFC10' THEN 1
          WHEN 'APIA_RFC10' THEN 2
          WHEN 'VPL_RFC10' THEN 3
