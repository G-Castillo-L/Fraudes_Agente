CREATE TEMP TABLE BIO_TRJ AS (
  WITH KEY_STATS AS (
    SELECT
      CTA_CVE, COUNT(1) AS CNT_KEYS
    FROM BIO_KEYS
    GROUP BY CTA_CVE
  ),
  BIO_OP AS (
    SELECT
      CONCAT(CAST(U.CTA_CVE AS STRING), '|', CAST(U.TRJ_NUM AS STRING)) AS ID_ROW,
      U.CTA_CVE,
      U.BLOQ2,
      IFNULL(S.CNT_KEYS, 0) AS CNT_KEYS,
      U.FCH_REP AS REF_FECHA,
      U.HRA_REP AS REF_HORA,
      'EXACTO_UNIV' AS REF_MODO,
      IF(EXTRACT(HOUR FROM U.HRA_REP) BETWEEN HR_OPEN AND HR_CLOSE, 1, 0) AS HAS_REF_IN_WINDOW,
      DATETIME(U.FCH_REP, U.HRA_REP) AS TS_REF,
      GREATEST(
        DATETIME(U.FCH_REP, TIME(HR_OPEN, 0, 0)),
        DATETIME_SUB(DATETIME(U.FCH_REP, U.HRA_REP), INTERVAL MAX_SAME_DAY_MIN MINUTE)
      ) AS TS_LOW,
      LEAST(
        DATETIME(U.FCH_REP, TIME(HR_CLOSE, 59, 59)),
        DATETIME_ADD(DATETIME(U.FCH_REP, U.HRA_REP), INTERVAL MAX_SAME_DAY_MIN MINUTE)
      ) AS TS_HIGH
    FROM (
      SELECT DISTINCT
        CTA_CVE, TRJ_NUM, FCH_REP, HRA_REP, BLOQ2
      FROM UNIV
      WHERE FCH_REP IS NOT NULL
        AND HRA_REP IS NOT NULL
    ) AS U
    LEFT JOIN KEY_STATS AS S
      ON U.CTA_CVE = S.CTA_CVE
  ),
  ROW_KEYS AS (
    SELECT
      O.ID_ROW, O.CTA_CVE, O.BLOQ2, O.CNT_KEYS,
      O.REF_FECHA, O.REF_HORA, O.REF_MODO,
      O.TS_REF, O.TS_LOW, O.TS_HIGH, O.HAS_REF_IN_WINDOW,
      K.TYPE, K.SRC, K.KEY_VAL, K.DOB6
    FROM BIO_OP AS O
    LEFT JOIN BIO_KEYS AS K
      ON O.CTA_CVE = K.CTA_CVE
  ),
  ENR_MET AS (
    SELECT
      B.ID_ROW, B.TYPE, B.SRC, B.KEY_VAL, B.DOB6,

      ARRAY_AGG(
        IF(
          E.TS_ENR BETWEEN B.TS_LOW AND B.TS_REF
          AND DATE(E.TS_ENR) = B.REF_FECHA,
