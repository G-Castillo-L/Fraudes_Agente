            E.TS_ENR AS TS_ENR,
            E.FLG_EXI AS FLG_EXI,
            E.FLG_EXI_TIP AS FLG_EXI_TIP,
            E.INE_FLG AS INE_FLG,
            E.CURP_FLG AS CURP_FLG,
            E.ENR_FLG AS ENR_FLG,
            DATETIME_DIFF(B.TS_REF, E.TS_ENR, MINUTE) AS DIFF_MIN
          ),
          NULL
        )
        IGNORE NULLS
        ORDER BY E.TS_ENR DESC
        LIMIT 1
      )[SAFE_OFFSET(0)] AS ENR_BEFORE,

      ARRAY_AGG(
        IF(
          E.TS_ENR BETWEEN B.TS_LOW AND B.TS_REF
          AND DATE(E.TS_ENR) = B.REF_FECHA
          AND E.FLG_EXI = 'EXITOSO',
          STRUCT(
            E.TS_ENR AS TS_ENR,
            E.FLG_EXI AS FLG_EXI,
            E.FLG_EXI_TIP AS FLG_EXI_TIP,
            E.INE_FLG AS INE_FLG,
            E.CURP_FLG AS CURP_FLG,
            E.ENR_FLG AS ENR_FLG,
            DATETIME_DIFF(B.TS_REF, E.TS_ENR, MINUTE) AS DIFF_MIN
          ),
          NULL
        )
        IGNORE NULLS
        ORDER BY E.TS_ENR DESC
        LIMIT 1
      )[SAFE_OFFSET(0)] AS ENR_BEFORE_OK,

      ARRAY_AGG(
        IF(
          B.HAS_REF_IN_WINDOW = 1
          AND E.TS_ENR > B.TS_REF
          AND E.TS_ENR <= B.TS_HIGH
          AND DATE(E.TS_ENR) = B.REF_FECHA,
          STRUCT(
            E.TS_ENR AS TS_ENR,
            E.FLG_EXI AS FLG_EXI,
            E.FLG_EXI_TIP AS FLG_EXI_TIP,
            E.INE_FLG AS INE_FLG,
            E.CURP_FLG AS CURP_FLG,
            E.ENR_FLG AS ENR_FLG,
            DATETIME_DIFF(E.TS_ENR, B.TS_REF, MINUTE) AS DIFF_MIN
          ),
          NULL
        )
        IGNORE NULLS
        ORDER BY E.TS_ENR ASC
        LIMIT 1
      )[SAFE_OFFSET(0)] AS ENR_AFTER,

       ARRAY_AGG(
        IF(
          B.HAS_REF_IN_WINDOW = 1
          AND E.TS_ENR > B.TS_REF
          AND E.TS_ENR <= B.TS_HIGH
          AND DATE(E.TS_ENR) = B.REF_FECHA
          AND E.FLG_EXI = 'EXITOSO',
          STRUCT(
            E.TS_ENR AS TS_ENR,
            E.FLG_EXI AS FLG_EXI,
            E.FLG_EXI_TIP AS FLG_EXI_TIP,
            E.INE_FLG AS INE_FLG,
            E.CURP_FLG AS CURP_FLG,
            E.ENR_FLG AS ENR_FLG,
            DATETIME_DIFF(E.TS_ENR, B.TS_REF, MINUTE) AS DIFF_MIN
          ),
          NULL
        )
        IGNORE NULLS
        ORDER BY E.TS_ENR ASC
        LIMIT 1
      )[SAFE_OFFSET(0)] AS ENR_AFTER_OK,

     STRING_AGG(
        IF(
          E.TS_ENR BETWEEN B.TS_LOW AND B.TS_REF
          AND DATE(E.TS_ENR) = B.REF_FECHA,
          FORMAT(
            '%s %s [%s]',
            FORMAT_DATETIME('%H:%M', E.TS_ENR),
            E.FLG_EXI,
            E.FLG_EXI_TIP
          ),
          NULL
        ),
        ' > '
        ORDER BY E.TS_ENR ASC
        LIMIT 5
      ) AS ENR_BEFORE_PATH,

      STRING_AGG(
        IF(
          B.HAS_REF_IN_WINDOW = 1
          AND E.TS_ENR > B.TS_REF
          AND E.TS_ENR <= B.TS_HIGH
          AND DATE(E.TS_ENR) = B.REF_FECHA,
          FORMAT(
            '%s %s [%s]',
            FORMAT_DATETIME('%H:%M', E.TS_ENR),
            E.FLG_EXI,
            E.FLG_EXI_TIP
          ),
          NULL
        ),
        ' > '
        ORDER BY E.TS_ENR ASC
        LIMIT 5
      ) AS ENR_AFTER_PATH,

    COUNTIF(
      E.TS_ENR BETWEEN B.TS_LOW AND B.TS_REF
      AND DATE(E.TS_ENR) = B.REF_FECHA
    ) AS ENR_BEFORE_CNT,

    COUNTIF(
      E.TS_ENR BETWEEN B.TS_LOW AND B.TS_REF
      AND DATE(E.TS_ENR) = B.REF_FECHA
      AND E.FLG_EXI = 'EXITOSO'
    ) AS ENR_BEFORE_OK_CNT,

    COUNTIF(
      B.HAS_REF_IN_WINDOW = 1
      AND E.TS_ENR > B.TS_REF
      AND E.TS_ENR <= B.TS_HIGH
      AND DATE(E.TS_ENR) = B.REF_FECHA
