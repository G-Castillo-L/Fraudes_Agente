        ]) AS X
        WHERE X IS NOT NULL AND X != ''
      ),
      '\n'
    ) AS TRJ_BIO_LOG
  FROM BIO_OP AS O
  LEFT JOIN BEST_PER_ROW AS B
    ON O.ID_ROW = B.ID_ROW
);

CREATE TEMP TABLE BIO_CTA AS (
  WITH CTA_LIST AS (
    SELECT DISTINCT CTA_CVE
    FROM UNIV
  ),
  KEY_STATS AS (
    SELECT
      CTA_CVE, COUNT(1) AS CNT_KEYS
    FROM BIO_KEYS
    GROUP BY CTA_CVE
  ),
  CTA_META AS (
    SELECT
      CTA_CVE, ANY_VALUE(CTE_CVE_UNICO) AS CTE_CVE_UNICO
    FROM UNIV
    GROUP BY CTA_CVE
  ),
  ENR_MATCH_HIST AS (
    SELECT
      K.CTA_CVE,
      K.TYPE AS MATCH_TYPE,
      K.SRC AS MATCH_SRC,
      K.KEY_VAL AS MATCH_KEY,
      K.DOB6,
      E.TS_ENR,
      E.ENR_CURP18
    FROM BIO_KEYS AS K
    LEFT JOIN BIO_ERN_KEYS_HIST AS E
      ON K.TYPE = E.TYPE
      AND K.KEY_VAL = E.KEY_VAL
      AND IF(K.TYPE = 'NAME_DOB', K.DOB6, '') = E.KEY_DOB6
  ),
  CTA_SUMMARY AS (
    SELECT
      CTA_CVE,
      COUNTIF(TS_ENR IS NOT NULL) AS CNT_ENR_MATCH
    FROM ENR_MATCH_HIST
    GROUP BY CTA_CVE
  ),
  CTA_BEST AS (
    SELECT
      CTA_CVE,
      TS_ENR,
      ENR_CURP18,
      MATCH_TYPE,
      MATCH_SRC,
      MATCH_KEY
    FROM ENR_MATCH_HIST
    WHERE TS_ENR IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY CTA_CVE
      ORDER BY TS_ENR DESC
    ) = 1
  )
  SELECT
    M.CTE_CVE_UNICO,
    L.CTA_CVE,
    B.ENR_CURP18 AS CTA_ENR_CURP18,
    IF(IFNULL(SU.CNT_ENR_MATCH, 0) > 0, 'SI', 'NO') AS CTA_ENR_EXISTE,
    CASE
      WHEN IFNULL(KS.CNT_KEYS, 0) = 0 THEN
        'NO KEYS'
      WHEN IFNULL(SU.CNT_ENR_MATCH, 0) = 0 THEN
        'SIN ENROLAMIENTO HISTORICO'
      ELSE
        FORMAT(
          'ULTIMO=%s | MATCH=%s/%s | KEY=%s',
          FORMAT_DATETIME('%F %T', B.TS_ENR),
          COALESCE(B.MATCH_TYPE, ''),
          COALESCE(B.MATCH_SRC, ''),
          COALESCE(B.MATCH_KEY, '')
        )
    END AS CTA_ENR_LOG
  FROM CTA_LIST AS L
  LEFT JOIN KEY_STATS AS KS
    ON L.CTA_CVE = KS.CTA_CVE
  LEFT JOIN CTA_SUMMARY AS SU
    ON L.CTA_CVE = SU.CTA_CVE
  LEFT JOIN CTA_BEST AS B
    ON L.CTA_CVE = B.CTA_CVE
  LEFT JOIN CTA_META AS M
    ON L.CTA_CVE = M.CTA_CVE
);

