      B.HAS_REF_IN_WINDOW = 1
      AND E.TS_ENR > B.TS_REF
      AND E.TS_ENR <= B.TS_HIGH
      AND DATE(E.TS_ENR) = B.REF_FECHA
      AND E.FLG_EXI = 'EXITOSO'
    ) AS ENR_AFTER_OK_CNT,

    FROM ROW_KEYS AS B
    LEFT JOIN BIO_ERN_KEYS AS E
      ON B.TYPE = E.TYPE
      AND B.KEY_VAL = E.KEY_VAL
      AND IF(B.TYPE = 'NAME_DOB', B.DOB6, '') = E.KEY_DOB6
    GROUP BY B.ID_ROW, B.TYPE, B.SRC, B.KEY_VAL, B.DOB6
  ),
  ENR_HIST_MET AS (
    SELECT
      B.ID_ROW, B.TYPE, B.SRC, B.KEY_VAL, B.DOB6,
      LOGICAL_OR(E.TS_ENR <= B.TS_REF) AS HAS_ENR_HIST_ANY,

      ARRAY_AGG(
        IF(
          E.TS_ENR <= B.TS_REF,
          STRUCT(
            E.TS_ENR AS TS_ENR,
            DATETIME_DIFF(B.TS_REF, E.TS_ENR, MINUTE) AS DIFF_MIN,
            DATETIME_DIFF(B.TS_REF, E.TS_ENR, DAY) AS DIFF_DAY
          ),
          NULL
        )
        IGNORE NULLS
        ORDER BY E.TS_ENR DESC
        LIMIT 1
      )[SAFE_OFFSET(0)] AS ENR_HIST_LAST_ANY
    FROM ROW_KEYS AS B
    LEFT JOIN BIO_ERN_KEYS_HIST AS E
      ON B.TYPE = E.TYPE
      AND B.KEY_VAL = E.KEY_VAL
      AND IF(B.TYPE = 'NAME_DOB', B.DOB6, '') = E.KEY_DOB6
    GROUP BY B.ID_ROW, B.TYPE, B.SRC, B.KEY_VAL, B.DOB6
  ),
  AUT_MET AS (
    SELECT
      B.ID_ROW, B.TYPE, B.SRC, B.KEY_VAL, B.DOB6,

      ARRAY_AGG(
        IF(
          A.TS_AUT BETWEEN B.TS_LOW AND B.TS_REF
          AND DATE(A.TS_AUT) = B.REF_FECHA,
          STRUCT(
            A.TS_AUT AS TS_AUT,
            A.RESP_AUT AS RESP_AUT,
            DATETIME_DIFF(B.TS_REF, A.TS_AUT, MINUTE) AS DIFF_MIN
          ),
          NULL
        )
        IGNORE NULLS
        ORDER BY A.TS_AUT DESC
        LIMIT 1
      )[SAFE_OFFSET(0)] AS AUT_BEFORE,

      ARRAY_AGG(
        IF(
          A.TS_AUT BETWEEN B.TS_LOW AND B.TS_REF
          AND DATE(A.TS_AUT) = B.REF_FECHA
          AND A.RESP_AUT = 'AUTENTICACION EXITOSA',
          STRUCT(
            A.TS_AUT AS TS_AUT,
            A.RESP_AUT AS RESP_AUT,
            DATETIME_DIFF(B.TS_REF, A.TS_AUT, MINUTE) AS DIFF_MIN
          ),
          NULL
        )
        IGNORE NULLS
        ORDER BY A.TS_AUT DESC
        LIMIT 1
      )[SAFE_OFFSET(0)] AS AUT_BEFORE_OK,

      ARRAY_AGG(
        IF(
          B.HAS_REF_IN_WINDOW = 1
          AND A.TS_AUT > B.TS_REF
          AND A.TS_AUT <= B.TS_HIGH
          AND DATE(A.TS_AUT) = B.REF_FECHA,
          STRUCT(
            A.TS_AUT AS TS_AUT,
            A.RESP_AUT AS RESP_AUT,
            DATETIME_DIFF(A.TS_AUT, B.TS_REF, MINUTE) AS DIFF_MIN
          ),
          NULL
        )
        IGNORE NULLS
        ORDER BY A.TS_AUT ASC
        LIMIT 1
      )[SAFE_OFFSET(0)] AS AUT_AFTER,

      ARRAY_AGG(
        IF(
          B.HAS_REF_IN_WINDOW = 1
          AND A.TS_AUT > B.TS_REF
          AND A.TS_AUT <= B.TS_HIGH
          AND DATE(A.TS_AUT) = B.REF_FECHA
          AND A.RESP_AUT = 'AUTENTICACION EXITOSA',
          STRUCT(
            A.TS_AUT AS TS_AUT,
            A.RESP_AUT AS RESP_AUT,
            DATETIME_DIFF(A.TS_AUT, B.TS_REF, MINUTE) AS DIFF_MIN
          ),
          NULL
        )
        IGNORE NULLS
        ORDER BY A.TS_AUT ASC
        LIMIT 1
      )[SAFE_OFFSET(0)] AS AUT_AFTER_OK,

      STRING_AGG(
        IF(
          A.TS_AUT BETWEEN B.TS_LOW AND B.TS_REF
          AND DATE(A.TS_AUT) = B.REF_FECHA,
          FORMAT(
            '%s %s',
            FORMAT_DATETIME('%H:%M', A.TS_AUT),
            A.RESP_AUT
          ),
          NULL
        ),
        ' > '
        ORDER BY A.TS_AUT ASC
        LIMIT 5
      ) AS AUT_BEFORE_PATH,

      STRING_AGG(
        IF(
          B.HAS_REF_IN_WINDOW = 1
          AND A.TS_AUT > B.TS_REF
          AND A.TS_AUT <= B.TS_HIGH
          AND DATE(A.TS_AUT) = B.REF_FECHA,
          FORMAT(
            '%s %s',
            FORMAT_DATETIME('%H:%M', A.TS_AUT),
            A.RESP_AUT
          ),
          NULL
        ),
        ' > '
        ORDER BY A.TS_AUT ASC
        LIMIT 5
      ) AS AUT_AFTER_PATH,

      COUNTIF(
        A.TS_AUT BETWEEN B.TS_LOW AND B.TS_REF
        AND DATE(A.TS_AUT) = B.REF_FECHA
      ) AS AUT_BEFORE_CNT,

      COUNTIF(
        A.TS_AUT BETWEEN B.TS_LOW AND B.TS_REF
        AND DATE(A.TS_AUT) = B.REF_FECHA
        AND A.RESP_AUT = 'AUTENTICACION EXITOSA'
      ) AS AUT_BEFORE_OK_CNT,

      COUNTIF(
        B.HAS_REF_IN_WINDOW = 1
        AND A.TS_AUT > B.TS_REF
        AND A.TS_AUT <= B.TS_HIGH
        AND DATE(A.TS_AUT) = B.REF_FECHA
      ) AS AUT_AFTER_CNT,

      COUNTIF(
        B.HAS_REF_IN_WINDOW = 1
        AND A.TS_AUT > B.TS_REF
        AND A.TS_AUT <= B.TS_HIGH
        AND DATE(A.TS_AUT) = B.REF_FECHA
        AND A.RESP_AUT = 'AUTENTICACION EXITOSA'
      ) AS AUT_AFTER_OK_CNT

    FROM ROW_KEYS AS B
    LEFT JOIN BIO_AUT_KEYS AS A
      ON B.TYPE = A.TYPE
      AND B.KEY_VAL = A.KEY_VAL
      AND IF(B.TYPE = 'NAME_DOB', B.DOB6, '') = A.KEY_DOB6
    GROUP BY B.ID_ROW, B.TYPE, B.SRC, B.KEY_VAL, B.DOB6
  ),
  KEY_STATUS_BASE AS (
    SELECT
      E.ID_ROW, E.TYPE, E.SRC, E.KEY_VAL, E.DOB6,
      O.BLOQ2,
      H.HAS_ENR_HIST_ANY,
      H.ENR_HIST_LAST_ANY,
      E.ENR_BEFORE, E.ENR_AFTER,

      E.ENR_BEFORE_CNT, E.ENR_BEFORE_OK_CNT,
      E.ENR_AFTER_CNT, E.ENR_AFTER_OK_CNT,
      E.ENR_BEFORE_PATH, E.ENR_AFTER_PATH,
      E.ENR_BEFORE_OK, E.ENR_AFTER_OK,

