      IF(TRIM(E.ENR_FLG) = "", NULL, TRIM(E.ENR_FLG)) AS ENR_FLG,
      IF(TRIM(E.CURP_FLG) = "", NULL, TRIM(E.CURP_FLG)) AS CURP_FLG,
      IF(TRIM(E.INE_FLG) = "", NULL, TRIM(E.INE_FLG)) AS INE_FLG,
      E.IUB,
      E.INE_CVE_ELE,
      E.PASAPORTE_NUM
