CREATE TEMP TABLE UNIV_INI AS (
  WITH 
  UNIV_INI_AUX AS (
    SELECT
      B.TIP_INF AS TIP_INF, A.CTE_CVE_UNICO, A.CTE_CVE, A.CTA_CVE, A.TRJ_NUM,
      A.IND_TIT, A.NUM_CONSECUTIVO_TRJ AS TRJ_SEQ, 
      A.TRJ_EDO_CVE, A.BLQ_TRJ_CVE, A.RAZON_BLQ_TRJ_CVE,
      IF(A.FCH_ALTA_TRJ IN (DATE(9999,12,31), DATE(1900,01,01)), NULL, A.FCH_ALTA_TRJ) AS FCH_ALTA_TRJ, 
      IF(A.FCH_EMB_TRJ IN (DATE(9999,12,31), DATE(1900,01,01)), NULL, A.FCH_EMB_TRJ) AS FCH_EMB_TRJ,
      IF(A.FCH_BLQ_TRJ IN (DATE(9999,12,31), DATE(1900,01,01)), NULL, A.FCH_BLQ_TRJ) AS FCH_BLQ_TRJ, 
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CTA_TRJ` AS A
    LEFT JOIN `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CTA` AS B
      ON (A.CTA_CVE = B.CTA_CVE)
    WHERE TRUE
      AND TRUNC(TRJ_NUM / 10000000000) NOT IN (479438, 421017)
      AND SAFE_CAST(IND_TIT AS NUMERIC) = 0
      AND 
      (
        (FCH_ALTA_TRJ BETWEEN FE_INI AND FE_FIN)
        OR (FCH_EMB_TRJ BETWEEN FE_INI AND FE_FIN)
        OR (FCH_BLQ_TRJ BETWEEN FE_INI AND FE_FIN)
      )
  ),
  EMBOZADAS AS (
    SELECT DISTINCT  
      SAFE_CAST(TRJ AS NUMERIC) AS TRJ, 
      SAFE_CAST(CTA_CVE AS NUMERIC) AS CTA_CVE,
      TIP_INF,
      USR AS USR_VPL_R05, 
      FCH_MOV AS FCH_MOV_R05,  
      HRA_MOV AS HRA_MOV_R05
    FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_EMBOSSER_MD_R05`
    WHERE TRUE
      AND FCH_MOV <= FE_FIN
      AND UPPER(TRIM(COD_DESC)) IN ('* NEW RECORD ADDED *','USER 5','USER 8','TEMP EMBOSSING NBR','ISSUE FLAG','EMBOSSER NAME 1','EMBOSSED NAME 1')
    QUALIFY ROW_NUMBER() OVER( PARTITION BY SAFE_CAST(TRJ AS NUMERIC) ORDER BY FCH_MOV, HRA_MOV) = 1
    ORDER BY FCH_MOV_R05 ,HRA_MOV_R05 NULLS LAST
  ),
  CREACIONES_TRJ AS (
    SELECT DISTINCT 
      IF(LENGTH(TRIM(CTE_CVE)) = 16, CTE_CVE, CONCAT(SAFE_CAST(CTE_CVE AS NUMERIC), LPAD(CONCAT(SAFE_CAST(FLG1 AS NUMERIC)),2, '0'))) AS TRJ, 
      CTE_CVE AS CTE_CVE_R09, FLG1, USR AS USR_VPL_CREA,
      FCH AS FCH_MOV_R09, HRA AS HRA_MOV_R09,
    FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_R09`
    WHERE TRUE
      AND FCH <= FE_FIN 
      AND UPPER(TRIM(DES)) IN ('* NEW RECORD ADDED *')
      AND SAFE_CAST(FLG1 AS NUMERIC) IS NOT NULL
      QUALIFY ROW_NUMBER() OVER( PARTITION BY IF(LENGTH(TRIM(CTE_CVE)) = 16,CTE_CVE,CONCAT(SAFE_CAST(CTE_CVE AS NUMERIC), LPAD(CONCAT(SAFE_CAST(FLG1 AS NUMERIC)), 2, '0'))) ORDER BY FCH,HRA NULLS LAST) = 1
  ),
  PREVIO AS (
    SELECT 
      A.TIP_INF AS TIP_INF_R, A.CTE_CVE_UNICO, A.CTA_CVE, A.TRJ_NUM, A.TRJ_EDO_CVE, A.BLQ_TRJ_CVE, A.RAZON_BLQ_TRJ_CVE,
      C.FCH_MOV_R05,C.HRA_MOV_R05,
      B.FCH_MOV_R09,B.HRA_MOV_R09,
      A.FCH_EMB_TRJ, A.FCH_ALTA_TRJ, A.FCH_BLQ_TRJ,
      CASE 
        WHEN A.FCH_EMB_TRJ IS NOT NULL THEN FCH_EMB_TRJ
        WHEN A.FCH_EMB_TRJ IS NULL AND A.TIP_INF = 110 AND A.TRJ_SEQ = 1 THEN FCH_ALTA_TRJ
        WHEN A.FCH_EMB_TRJ IS NULL AND A.TIP_INF = 110 AND A.TRJ_SEQ <> 1 THEN FCH_BLQ_TRJ
        WHEN A.FCH_EMB_TRJ IS NULL AND A.TIP_INF <> 110 AND A.CTA_CVE = A.TRJ_NUM THEN FCH_ALTA_TRJ
        WHEN A.FCH_EMB_TRJ IS NULL AND A.TIP_INF <> 110 AND A.CTA_CVE <> A.TRJ_NUM THEN FCH_BLQ_TRJ
      END FCH_TRJ_MOD,
      C.USR_VPL_R05,B.USR_VPL_CREA
    FROM UNIV_INI_AUX AS A
    LEFT JOIN CREACIONES_TRJ AS B
      ON (A.TRJ_NUM=SAFE_CAST(B.TRJ AS NUMERIC))
    LEFT JOIN EMBOZADAS C
      ON (A.TRJ_NUM=SAFE_CAST(C.TRJ AS NUMERIC))
  ),
  BASE AS (
    SELECT 
      *,
      COALESCE(FCH_MOV_R05,FCH_MOV_R09,FCH_EMB_TRJ,FCH_TRJ_MOD) FCH_REP,
      COALESCE(HRA_MOV_R05,HRA_MOV_R09,NULL) HRA_REP,
      CASE WHEN FCH_MOV_R05 IS NOT NULL OR FCH_EMB_TRJ IS NOT NULL THEN 1 ELSE 0 END FLG_EMBO
    FROM PREVIO
    WHERE COALESCE(HRA_MOV_R05,HRA_MOV_R09,NULL) IS NOT NULL
  )
  SELECT *
  FROM BASE
  WHERE TRUE 
    AND FCH_REP >= FE_INI
  QUALIFY ROW_NUMBER() OVER( PARTITION BY CTA_CVE, FCH_REP ORDER BY FCH_REP,FLG_EMBO DESC,HRA_REP DESC)=1
);
CREATE TEMP TABLE UNIV AS (
  WITH
  UNIV_PRTNCIA AS (
    SELECT 
      A.CODIGO_ACCION, A.NUMERO_CUENTA AS CTA_CVE,
      COALESCE(B.TRJ_NUM, A.NUMERO_TARJETA) AS TRJ_NUM, A.TIENDA_AUTENTICACION AS TDA_ATENCION, A.ID AS ID_ATENCION,
      A.FECHA, A.HORA, TRIM(UPPER(CORREO_ELECTRONICO)) AS EMAIL, CAST(SUBSTR(CAST(NUMERO_CELULAR AS STRING), -10) AS NUMERIC) AS CEL
    FROM `MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_PRTNCIA_DATOS` AS A
    INNER JOIN (SELECT DISTINCT CTA_CVE, TRJ_NUM, FCH_REP FROM UNIV_INI) AS B
      ON
        A.NUMERO_CUENTA = B.CTA_CVE 
        AND (A.FECHA = B.FCH_REP)
    WHERE TRUE
      AND TRIM(A.CODIGO_ACCION) IN ("EMBO", "TPRO", "VALE", "REPO") 
    QUALIFY ROW_NUMBER() OVER (PARTITION BY FECHA, TRJ_NUM ORDER BY FECHA DESC, HORA DESC) = 1 
  ),
  UNIV_PRTNCIA_AGG_TRJ AS (
    SELECT
      CTA_CVE, TRJ_NUM,
      COUNT(1) AS CNT_PRTNCIA,
      STRING_AGG(
        FORMAT(
          '%s %s | ACC=%s | CTA=%s | TDA=%s\nID=%s | EMAIL=%s | CEL=%s',
          FORMAT_DATE('%F', FECHA),
          COALESCE(CAST(HORA AS STRING), ''),
          COALESCE(CODIGO_ACCION, ''),
          COALESCE(CAST(CTA_CVE AS STRING), ''),
          COALESCE(CAST(TDA_ATENCION AS STRING), ''),
          COALESCE(CAST(ID_ATENCION AS STRING), ''),
          COALESCE(EMAIL, ''),
          COALESCE(CAST(CEL AS STRING), '')
        ),
        '\n'
        ORDER BY FECHA DESC, HORA DESC
      ) AS LOG_PRTNCIA
    FROM UNIV_PRTNCIA
    GROUP BY CTA_CVE, TRJ_NUM
  ),
  UNIV_PRTNCIA_AGG_CTA AS (
    SELECT
      CTA_CVE,
      COUNT(1) AS CNT_PRTNCIA,
      STRING_AGG(
        FORMAT(
          'TRJ_NUM=%s | %s %s | ACC=%s | CTA=%s | TDA=%s\nID=%s | EMAIL=%s | CEL=%s',
          COALESCE(CAST(TRJ_NUM AS STRING), ''),
          FORMAT_DATE('%F', FECHA),
          COALESCE(CAST(HORA AS STRING), ''),
          COALESCE(CODIGO_ACCION, ''),
          COALESCE(CAST(CTA_CVE AS STRING), ''),
          COALESCE(CAST(TDA_ATENCION AS STRING), ''),
          COALESCE(CAST(ID_ATENCION AS STRING), ''),
          COALESCE(EMAIL, ''),
          COALESCE(CAST(CEL AS STRING), '')
        ),
        '\n'
        ORDER BY FECHA DESC, HORA DESC
      ) AS LOG_PRTNCIA
    FROM UNIV_PRTNCIA
    GROUP BY CTA_CVE
  ),
  UNIV_VPL AS (
    SELECT DISTINCT
      A.CTA_CVE,
      CONCAT(
        TRIM(COALESCE(CTE_NOM, "")), " ",
        TRIM(COALESCE(CTE_APE_PAT, "")), " ",
        TRIM(COALESCE(CTE_APE_MAT, ""))
      ) AS NOMBRE,
      IF(REGEXP_CONTAINS(TRIM(CTE_CVE_RFC), r"^0+"), NULL, SUBSTR(TRIM(CTE_CVE_RFC), 1, 13)) AS CTE_CVE_RFC,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL AS STRING)), -10) AS NUMERIC) AS TEL,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_CEL AS STRING)), -10) AS NUMERIC) AS CEL,
      UPPER(TRIM(CTE_EMA)) AS EMAIL,
      CONCAT(
        TRIM(COALESCE(CTE_DES_DIR_UNO, "")), ", ",
        TRIM(COALESCE(CTE_DES_DIR_DOS, "")), ", ",
        COALESCE(CAST(CDP_CVE AS STRING), ""), ", ",
        TRIM(COALESCE(CTE_DES_CIU, ""))
      ) AS DIRECCION,
      SAFE_CAST(CDP_CVE AS STRING) AS CDP_CVE,
      SEX_CVE AS SEXO,
      CTE_FCH_NAC AS FCH_NAC,
      CTE_FCH_ALT AS FCH_APERTURA,
      TRIM(CTE_EMPR) AS EMPLEO,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL_OFI AS STRING)), -10) AS NUMERIC) AS TEL_OFI,
      TRIM(CTE_CONYUGE) AS NOM_CONYUGE,
      TRIM(CTE_NOM_REFERENCIA1) AS NOM_REF1,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL_REFERENCIA1 AS STRING)), -10) AS NUMERIC) AS TEL_REF1,
      TRIM(CTE_NOM_REFERENCIA2) AS NOM_REF2,
      SAFE_CAST(SUBSTR(ZEROS_TO_NULL(CAST(CTE_TEL_REFERENCIA2 AS STRING)), -10) AS NUMERIC) AS TEL_REF2
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CLIE_FTES_VPL` AS A
    INNER JOIN (
      SELECT DISTINCT CTA_CVE FROM UNIV_INI
    ) AS U
      ON A.CTA_CVE = U.CTA_CVE
  ),
  UNIV_SDO AS (
    SELECT
      CTA_CVE, BR_SOLIC_CVE, CTA_FCH_SOL, CTA_EDO_CVE, CTA_NIV_MOR, CTA_IMP_LIM_CRD, CTA_SDO_ACT, CTA_HIST_PAGOS, TDA_APE,
      CONCAT(CCR_CVE_BLQ_UNO, RAZON_BLQ_UNO_CVE) AS BLOQ1,
      CONCAT(CCR_CVE_BLQ_DOS, RAZON_BLQ_DOS_CVE) AS BLOQ2,
      CTA_DEV, CTA_PAG, CTA_IMP, BR_TIPO_3, TIP_INF
      
      FROM (
        SELECT
          A.CTA_CVE, NULLIF(A.BR_SOLIC_CVE, 0) AS BR_SOLIC_CVE, CTA_FCH_SOL, CTA_EDO_CVE, CTA_NIV_MOR,
          CCR_CVE_BLQ_UNO, RAZON_BLQ_UNO_CVE, CCR_CVE_BLQ_DOS, RAZON_BLQ_DOS_CVE,
          CTA_IMP_LIM_CRD, CTA_SDO_ACT, CTA_HIST_PAGOS, 
          SAFE_CAST(CTA_TDA_APE AS INT64) AS TDA_APE,
          CTA_IMP_DEV_LTD AS CTA_DEV, CTA_IMP_PAG_LTD AS CTA_PAG, CTA_IMP_MCMP_LTD AS CTA_IMP,
          SUBSTR(SAFE_CAST(BR_TIPO AS STRING), 1, 3) AS BR_TIPO_3,
          TIP_INF
        FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VFAC_SDO_CTA_MES` AS A
        INNER JOIN (
          SELECT DISTINCT CTA_CVE FROM UNIV_INI
        ) AS U
          ON A.CTA_CVE = U.CTA_CVE
        WHERE TRUE
          AND ANIO = CUR_ANIO
          AND MES = CUR_MES
      )
  ), 
  UNIV_FICO AS (
    SELECT 
      NULLIF(SAFE_CAST(A.BR_SOLIC_CVE AS NUMERIC), 0) AS BR_SOLIC_CVE, FCH_SOL, HRA_SOL,
      BRAND, CL,
      STT_FICO, STT_SIMP_FICO, TRIM(BR_RFC) AS FICO_RFC
    FROM `crp-pro-dwh-semanticagold.MUS_PRO_DWH_VIEWS_ODS.VFAC_PREVFRAU_REP_SOL_FICO` AS A
    INNER JOIN (SELECT DISTINCT BR_SOLIC_CVE FROM UNIV_SDO) AS U
      ON NULLIF(SAFE_CAST(A.BR_SOLIC_CVE AS NUMERIC), 0) = U.BR_SOLIC_CVE
  ),
  APIA_F AS (
    SELECT DISTINCT
      A.BR_SOLIC_CVE,
      TRIM(A.BR_CURP) AS APIA_CURP,
      TRIM(A.BR_RFC) AS APIA_RFC,
      SUBSTR(SAFE_CAST(A.BR_TIPO AS STRING), 1, 3) AS BR_TIPO_3,
      A.BR_ORG AS TIP_INF
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VFAC_APIA` AS A
    INNER JOIN (
      SELECT DISTINCT
        BR_SOLIC_CVE, BR_TIPO_3, TIP_INF
      FROM UNIV_SDO
      WHERE BR_SOLIC_CVE IS NOT NULL
    ) AS K
      ON A.BR_SOLIC_CVE = K.BR_SOLIC_CVE
      AND SUBSTR(SAFE_CAST(A.BR_TIPO AS STRING), 1, 3) = K.BR_TIPO_3
      AND SAFE_CAST(A.BR_ORG AS STRING) = SAFE_CAST(K.TIP_INF AS STRING)
  )
  SELECT 
    C.BR_SOLIC_CVE,
    A.*,
    B.* EXCEPT(CTA_CVE),
    C.* EXCEPT(CTA_CVE,BR_SOLIC_CVE, BR_TIPO_3, TIP_INF),
    D.* EXCEPT(BR_SOLIC_CVE),
    E.* EXCEPT(BR_SOLIC_CVE),
    IF(IFNULL(P.CNT_PRTNCIA, 0) > 0, 1, IF(IFNULL(PC.CNT_PRTNCIA, 0) > 0, 1, 0)) AS FLG_PRTNCIA_MATCH,
    COALESCE(P.LOG_PRTNCIA, PC.LOG_PRTNCIA) AS PRTNCIA_LOG
  FROM UNIV_INI AS A
  LEFT JOIN UNIV_PRTNCIA_AGG_TRJ AS P
    ON A.TRJ_NUM = P.TRJ_NUM
  LEFT JOIN UNIV_PRTNCIA_AGG_CTA AS PC
    ON A.CTA_CVE = PC.CTA_CVE
  LEFT JOIN UNIV_VPL AS B
    ON A.CTA_CVE = B.CTA_CVE
  LEFT JOIN UNIV_SDO AS C
    ON A.CTA_CVE = C.CTA_CVE
  LEFT JOIN UNIV_FICO AS D
    ON C.BR_SOLIC_CVE = D.BR_SOLIC_CVE
  LEFT JOIN APIA_F AS E
    ON C.BR_SOLIC_CVE = E.BR_SOLIC_CVE
);
CREATE TEMP TABLE BIO_KEYS AS (
  WITH CTA_SRC AS (
    SELECT DISTINCT
      CTA_CVE, NOMBRE, CTE_CVE_RFC, APIA_CURP, APIA_RFC, FICO_RFC
    FROM UNIV
  ),
  PRE AS (
    SELECT
      CTA_CVE,
      NORM_CURP18(CTE_CVE_RFC) AS K_CURP18_VPL,
      NORM_KEY10(CTE_CVE_RFC) AS K_KEY10_VPL,
      NORM_CURP18(APIA_CURP) AS K_CURP18_APIA,
      NORM_KEY10(APIA_RFC) AS K_KEY10_APIA,
      NORM_KEY10(FICO_RFC) AS K_KEY10_FICO,
      UPPER(TRANSLATE(TRIM(IFNULL(NOMBRE, "")), UNICO, ASCI)) AS K_NOM_N,
      CASE
        WHEN IS_CURP18(NORM_CURP18(CTE_CVE_RFC)) THEN SUBSTR(NORM_CURP18(CTE_CVE_RFC), 5, 6)
        WHEN IS_CURP18(NORM_CURP18(APIA_CURP)) THEN SUBSTR(NORM_CURP18(APIA_CURP), 5, 6)
        WHEN IS_CURP10(NORM_KEY10(CTE_CVE_RFC)) THEN SUBSTR(NORM_KEY10(CTE_CVE_RFC), 5, 6)
        ELSE NULL
      END AS DOB6
    FROM CTA_SRC
  )
  SELECT CTA_CVE, 'CURP' AS TYPE, 'VPL_CURP18' AS SRC, K_CURP18_VPL AS KEY_VAL, DOB6
  FROM PRE
  WHERE K_CURP18_VPL IS NOT NULL
    AND IS_CURP18(K_CURP18_VPL)

  UNION DISTINCT
  SELECT CTA_CVE, 'CURP' AS TYPE, 'APIA_CURP18' AS SRC, K_CURP18_APIA AS KEY_VAL, DOB6
  FROM PRE
  WHERE K_CURP18_APIA IS NOT NULL
    AND IS_CURP18(K_CURP18_APIA)

  UNION DISTINCT
  SELECT CTA_CVE, 'KEY10' AS TYPE, 'VPL_RFC10' AS SRC, K_KEY10_VPL AS KEY_VAL, DOB6
  FROM PRE
  WHERE K_KEY10_VPL IS NOT NULL

  UNION DISTINCT
  SELECT CTA_CVE, 'KEY10' AS TYPE, 'APIA_RFC10' AS SRC, K_KEY10_APIA AS KEY_VAL, DOB6
  FROM PRE
  WHERE K_KEY10_APIA IS NOT NULL

  UNION DISTINCT
  SELECT CTA_CVE, 'KEY10' AS TYPE, 'FICO_RFC10' AS SRC, K_KEY10_FICO AS KEY_VAL, DOB6
  FROM PRE
  WHERE K_KEY10_FICO IS NOT NULL

  UNION DISTINCT
  SELECT CTA_CVE, 'NAME_DOB' AS TYPE, 'VPL_NAME_DOB' AS SRC, K_NOM_N AS KEY_VAL, DOB6
  FROM PRE
  WHERE K_NOM_N IS NOT NULL
    AND DOB6 IS NOT NULL
);

CREATE TEMP TABLE BIO_ERN_KEYS AS (
  WITH KEY_CURP AS (
    SELECT DISTINCT
      KEY_VAL AS CURP18
    FROM BIO_KEYS
    WHERE TYPE = 'CURP'
  ),
  KEY_KEY10 AS (
    SELECT DISTINCT
      KEY_VAL AS KEY10
    FROM BIO_KEYS
    WHERE TYPE = 'KEY10'
  ),
  KEY_NAME_DOB AS (
    SELECT DISTINCT
      KEY_VAL AS NOM_N, DOB6
    FROM BIO_KEYS
    WHERE TYPE = 'NAME_DOB'
  ),
  PRE AS (
    SELECT DISTINCT
      DATETIME(E.FCH_ENR, E.HRA_ENR) AS TS_ENR,
      NORM_KEY10(E.CTE_CVE) AS KEY10,
