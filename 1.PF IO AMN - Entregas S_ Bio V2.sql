CREATE TEMP FUNCTION ZEROS_TO_NULL(s STRING) AS (
  CASE
    WHEN s IS NULL THEN NULL
    WHEN TRIM(s) = "" THEN NULL
    WHEN REGEXP_CONTAINS(TRIM(s), r"^0+$") THEN NULL
    ELSE TRIM(s)
  END
);
CREATE TEMP FUNCTION NORM_KEY10(x STRING) AS (
  SUBSTR(UPPER(REGEXP_REPLACE(TRIM(IFNULL(x, "")), r'[^A-Z0-9]', "")), 1, 10)
);
CREATE TEMP FUNCTION NORM_CURP18(x STRING) AS (
  SUBSTR(UPPER(REGEXP_REPLACE(TRIM(IFNULL(x, "")), r'[^A-Z0-9]', "")), 1, 18)
);
CREATE TEMP FUNCTION IS_CURP18(x STRING) AS (
  REGEXP_CONTAINS(x, r'^[A-Z]{4}[0-9]{6}[A-Z0-9]{8}$')
);
CREATE TEMP FUNCTION IS_CURP10(x STRING) AS (
  REGEXP_CONTAINS(x, r'^[A-Z]{4}[0-9]{6}$')
);
CREATE TEMP FUNCTION NORM_TDA_NUM(x STRING) AS (
  SAFE_CAST(REGEXP_EXTRACT(CAST(x AS STRING), r'\d+') AS INT64)
);

