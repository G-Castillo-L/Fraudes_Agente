DECLARE FCH_INI DATE DEFAULT DATE(2026, 5, 1);
DECLARE FCH_FIN DATE DEFAULT DATE(2026, 5, 22);

CREATE TEMP FUNCTION ID16_NUM(x ANY TYPE) AS (
  CASE
    WHEN LENGTH(CAST(SAFE_CAST(SUBSTR(CAST(x AS STRING), -16) AS NUMERIC) AS STRING)) < 13 THEN NULL
    ELSE SAFE_CAST(SUBSTR(CAST(x AS STRING), -16) AS NUMERIC)
  END
);


CREATE TEMP TABLE CTAS_REV AS (
  SELECT CAST(x AS NUMERIC) AS CTA_CVE
  FROM UNNEST([
    '13000003715674'

  ]) AS x
);

CREATE TEMP TABLE CTA_TRJ AS (
  SELECT DISTINCT
    CTA_CVE, TRJ_NUM
  FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_CTA_TRJ`
  INNER JOIN CTAS_REV USING (CTA_CVE)
);

CREATE TEMP TABLE POS_TRN AS (
  WITH
  POS_BASE AS (
    SELECT DISTINCT
      B.CTA_CVE AS CTA_CVE_MATCH,

      ID16_NUM(A.CTA_CVE) AS TRJ_NUM,
      ID16_NUM(A.CTE_PRM_CRM) AS CTE_PRM_CRM,
      A.FCH_FCH,
      SAFE.PARSE_TIME('%H%M', LPAD(CAST(SAFE_CAST(A.HRA_HRA AS INT64) AS STRING), 4, '0')) AS HRA_HRA,
      SAFE_CAST(A.NUM_TER AS INT64) AS NUM_TER,
      SAFE_CAST(A.NUM_BOL AS INT64) AS BOL,
      SAFE_CAST(A.TDA_CVE AS INT64) AS TDA_CVE,
      SAFE_CAST(A.VND_CVE AS NUMERIC) AS VND_CVE,
      SAFE_CAST(A.NUM_REN AS INT64) AS NUM_REN,

      SAFE_CAST(A.IMP_TRN_BOL AS NUMERIC) AS TRN_IMP,
      SAFE_CAST(A.IMP_DESC_BOL AS NUMERIC) AS IMP_DESC_BOL,
      SAFE_CAST(A.IMP_RBJ_BOL AS NUMERIC) AS IMP_RBJ_BOL,
      SAFE_CAST(A.IMP_TRN_RGL AS NUMERIC) AS IMP_TRN_RGL,
      SAFE_CAST(A.IMP_SKU_TRN AS NUMERIC) AS IMP_SKU_TRN,
      SAFE_CAST(A.IMP_DESC_SKU_TRN AS NUMERIC) AS IMP_DESC_SKU_TRN,

      COALESCE(
        NULLIF(TRIM(CAST(A.NUM_SOMS AS STRING)), '0'),
        NULLIF(TRIM(CAST(A.NUM_OMS AS STRING)), '')
      ) AS SOMS_OMS,

      SAFE_CAST(A.TTR_CVE AS INT64) AS TTR_CVE,
      SAFE_CAST(A.TTR_STATUS AS INT64) AS TTR_STATUS,
      SAFE_CAST(A.DISP_VTA_CVE AS INT64) AS DISP_VTA_CVE,
      SAFE_CAST(A.CANAL_CVE AS INT64) AS CANAL_CVE,
      SAFE_CAST(A.RDE_CVE AS INT64) AS RDE_CVE,
      SAFE_CAST(A.TDA_CVE_REC AS INT64) AS TDA_CVE_REC,
      SAFE_CAST(A.NUM_CELULAR AS STRING) AS NUM_CELULAR,

      A.CTE_CVE_ORI,
      A.TDA_CVE_ORI,
      A.FCH_FCH_ORI,
      A.NUM_TER_ORI,
      A.NUM_BOL_ORI,
      A.VND_CVE_ORI,
      CAST(A.SKU_CVE AS STRING) AS SKU_CVE
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VFAC_POS_TRN` AS A
    INNER JOIN CTA_TRJ AS B
      ON (
        STRPOS(CAST(A.CTA_CVE AS STRING), CAST(B.TRJ_NUM AS STRING)) > 0
        OR STRPOS(CAST(A.CTE_PRM_CRM AS STRING), CAST(B.TRJ_NUM AS STRING)) > 0
        OR STRPOS(CAST(A.CTE_CVE_ORI AS STRING), CAST(B.TRJ_NUM AS STRING)) > 0
        OR STRPOS(CAST(A.CTA_CVE AS STRING), CAST(B.CTA_CVE AS STRING)) > 0
        OR STRPOS(CAST(A.CTE_PRM_CRM AS STRING), CAST(B.CTA_CVE AS STRING)) > 0
        OR STRPOS(CAST(A.CTE_CVE_ORI AS STRING), CAST(B.CTA_CVE AS STRING)) > 0
      )
    WHERE TRUE
      AND A.FCH_FCH BETWEEN FCH_INI AND FCH_FIN
  ),

  CAT_SKU AS (
    SELECT DISTINCT
      CAST(SKU_CVE AS STRING) AS SKU_CVE,
      TRIM(UPPER(SKU_DES)) AS SKU_DES
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VDIM_PROD_EXTR`
    QUALIFY ROW_NUMBER() OVER(PARTITION BY SKU_CVE ORDER BY FCH_CARGA DESC) = 1
  ),

  POS_AGG AS (
    SELECT
      MAX(A.CTA_CVE_MATCH) AS CTA_CVE,
      A.TRJ_NUM, A.CTE_PRM_CRM, A.FCH_FCH, A.HRA_HRA,
      A.TDA_CVE, A.NUM_TER, A.BOL, A.TRN_IMP,
      MAX(A.IMP_DESC_BOL) AS IMP_DESC_BOL,
      MAX(A.IMP_RBJ_BOL) AS IMP_RBJ_BOL,
      SUM(A.IMP_TRN_RGL) AS IMP_TRN_RGL,
      A.NUM_CELULAR,
      A.VND_CVE,

      STRING_AGG(DISTINCT A.SOMS_OMS, '\n' ORDER BY A.SOMS_OMS) AS SOMS_OMS,

      MAX(CASE WHEN A.RDE_CVE <> 0 AND A.TTR_CVE IN (2, 3) THEN 1 ELSE 0 END) AS IS_DEV_POS,

      STRING_AGG(
        CONCAT(
          CAST(A.NUM_REN AS STRING),
          ' - SKU CVE: ', COALESCE(A.SKU_CVE, ''),
          ' (', COALESCE(C.SKU_DES, ''), ')',
          ' - IMP ORIGINAL: ', COALESCE(FORMAT("$%'.2f", A.IMP_SKU_TRN), '$0.00'),
          ' | IMP DESCONTADO: ', COALESCE(FORMAT("$%'.2f", A.IMP_DESC_SKU_TRN), '$0.00'),
          ' | IMP PAGADO: ', COALESCE(FORMAT("$%'.2f", A.IMP_TRN_RGL), '$0.00')
        ),
        '\n'
        ORDER BY A.NUM_REN
      ) AS SKU_AGG,

      STRING_AGG(
        DISTINCT CONCAT(
          COALESCE(CAST(A.CTE_CVE_ORI AS STRING), '0'),
          ' - TDA: ', COALESCE(CAST(A.TDA_CVE_ORI AS STRING), ''),
          ' - FCH: ', COALESCE(CAST(A.FCH_FCH_ORI AS STRING), ''),
          ' - TERM: ', COALESCE(CAST(SAFE_CAST(A.NUM_TER_ORI AS INT64) AS STRING), '0'),
          ' - BOL: ', COALESCE(CAST(SAFE_CAST(A.NUM_BOL_ORI AS INT64) AS STRING), '0'),
          ' - VND: ', COALESCE(CAST(A.VND_CVE_ORI AS STRING), '0')
        ),
        '\n'
      ) AS ORI_AGG,

      A.TTR_CVE, A.TTR_STATUS, A.DISP_VTA_CVE, A.CANAL_CVE, A.RDE_CVE,
      STRING_AGG(DISTINCT CAST(A.TDA_CVE_REC AS STRING), '\n' ORDER BY CAST(A.TDA_CVE_REC AS STRING)) AS TDA_CVE_REC
    FROM POS_BASE AS A
    LEFT JOIN CAT_SKU AS C
      USING (SKU_CVE)
    GROUP BY
      A.TRJ_NUM, A.CTE_PRM_CRM, A.FCH_FCH, A.HRA_HRA,
      A.TDA_CVE, A.NUM_TER, A.BOL, A.TRN_IMP,
      A.NUM_CELULAR, A.VND_CVE,
      A.TTR_CVE, A.TTR_STATUS, A.DISP_VTA_CVE, A.CANAL_CVE, A.RDE_CVE
  )

  SELECT
    A.CTA_CVE, A.TRJ_NUM, A.CTE_PRM_CRM, A.FCH_FCH, A.HRA_HRA,
    A.TDA_CVE, A.NUM_TER, A.BOL, A.TRN_IMP,
    A.IMP_DESC_BOL, A.IMP_RBJ_BOL, A.IMP_TRN_RGL, A.NUM_CELULAR,
    A.IS_DEV_POS, A.VND_CVE,
    A.SKU_AGG, A.ORI_AGG, A.SOMS_OMS,

    CONCAT(TRIM(UPPER(E.TTR_DES_FTE)), ' / ', TRIM(UPPER(E.TTR_DES))) AS TIP_TRANSA,
    STRING_AGG(DISTINCT TRIM(UPPER(G.DISP_VTA_DES)), '\n' ORDER BY TRIM(UPPER(G.DISP_VTA_DES))) AS DISPOSITIVO,
    STRING_AGG(DISTINCT TRIM(UPPER(H.CANAL_DES)), '\n' ORDER BY TRIM(UPPER(H.CANAL_DES))) AS CANAL,
    STRING_AGG(DISTINCT TRIM(UPPER(I.RDE_DESC)), '\n' ORDER BY TRIM(UPPER(I.RDE_DESC))) AS DES_MOT_DEV,
    A.TDA_CVE_REC
  FROM POS_AGG AS A
  LEFT JOIN `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VCIS_TIP_POS_TRN` AS E
    ON A.TTR_CVE = SAFE_CAST(E.TTR_CVE AS INT64)
    AND A.TTR_STATUS = SAFE_CAST(E.TTR_STATUS AS INT64)
  LEFT JOIN `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VCIS_DISP_VTA` AS G
    ON A.DISP_VTA_CVE = SAFE_CAST(G.DISP_VTA_CVE AS INT64)
  LEFT JOIN `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VCIS_CANAL` AS H
    ON A.CANAL_CVE = SAFE_CAST(H.CANAL_CVE AS INT64)
  LEFT JOIN `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VCIS_MOT_DEV` AS I
    ON A.RDE_CVE = SAFE_CAST(I.RDE_CVE AS INT64)
  GROUP BY
    A.CTA_CVE, A.TRJ_NUM, A.CTE_PRM_CRM, A.FCH_FCH, A.HRA_HRA,
    A.TDA_CVE, A.NUM_TER, A.BOL, A.TRN_IMP,
    A.IMP_DESC_BOL, A.IMP_RBJ_BOL, A.IMP_TRN_RGL, A.NUM_CELULAR,
    A.IS_DEV_POS, A.VND_CVE,
    A.SKU_AGG, A.ORI_AGG, A.SOMS_OMS,
    TIP_TRANSA, A.TDA_CVE_REC
);

CREATE TEMP TABLE TIP_PAG AS (
  WITH
  TIP_PAG_BASE AS (
    SELECT DISTINCT
      A.FCH_FCH,
      SAFE_CAST(A.TDA_CVE AS INT64) AS TDA_CVE,
      SAFE_CAST(A.NUM_TER AS INT64) AS NUM_TER,
      SAFE_CAST(A.NUM_BOL AS INT64) AS BOL,
      SAFE_CAST(A.PLAN_CVE AS STRING) AS PLAN_CVE,
      SAFE_CAST(A.BAN_CVE AS STRING) AS BAN_CVE,
      SAFE_CAST(A.TPD_CVE AS STRING) AS TPD_CVE,
      SAFE_CAST(A.MED_ING_TRJ_CVE AS STRING) AS MED_ING_TRJ_CVE
    FROM `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VFAC_TIP_PAG` AS A
    INNER JOIN (
      SELECT DISTINCT
        FCH_FCH, TDA_CVE, NUM_TER, BOL
      FROM POS_TRN
    ) AS B
      ON B.FCH_FCH = A.FCH_FCH
      AND B.TDA_CVE = SAFE_CAST(A.TDA_CVE AS INT64)
      AND B.NUM_TER = SAFE_CAST(A.NUM_TER AS INT64)
      AND B.BOL = SAFE_CAST(A.NUM_BOL AS INT64)
    WHERE TRUE
      AND A.FCH_FCH BETWEEN FCH_INI AND FCH_FIN
  ),

  TIP_PAG_DET AS (
    SELECT
      A.FCH_FCH, A.TDA_CVE, A.NUM_TER, A.BOL,
      A.PLAN_CVE,
      TRIM(UPPER(C.BAN_DES_UNO)) AS BANCO,
      TRIM(UPPER(D.TPD_DES)) AS TIP_PAGO,
      TRIM(UPPER(F.MED_ING_TRJ_DES)) AS MED_ING
    FROM TIP_PAG_BASE AS A
    LEFT JOIN `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VCIS_BAN` AS C
      ON A.BAN_CVE = SAFE_CAST(C.BAN_CVE AS STRING)
    LEFT JOIN `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VCIS_TIP_PAG` AS D
      ON A.TPD_CVE = SAFE_CAST(D.TPD_CVE AS STRING)
    LEFT JOIN `crp-pro-dwh-semanticagold.EIL_DP_VDWH.VCIS_MED_ING_TRJ` AS F
      ON A.MED_ING_TRJ_CVE = SAFE_CAST(F.MED_ING_TRJ_CVE AS STRING)
  )

  SELECT
    FCH_FCH, TDA_CVE, NUM_TER, BOL,
    STRING_AGG(DISTINCT PLAN_CVE, '\n' ORDER BY PLAN_CVE) AS PLAN_CVE,
    STRING_AGG(DISTINCT BANCO, '\n' ORDER BY BANCO) AS BANCO,
    STRING_AGG(DISTINCT TIP_PAGO, '\n' ORDER BY TIP_PAGO) AS TIP_PAGO,
    STRING_AGG(DISTINCT MED_ING, '\n' ORDER BY MED_ING) AS MED_ING
  FROM TIP_PAG_DET
  GROUP BY
    FCH_FCH, TDA_CVE, NUM_TER, BOL
);

-- SELECT FINAL
SELECT DISTINCT
  A.CTA_CVE,
  A.TRJ_NUM,
  A.CTE_PRM_CRM,
  A.FCH_FCH AS FECHA,
  A.HRA_HRA AS HORA,
  A.TDA_CVE AS TIENDA,
  A.NUM_TER AS TERMINAL,
  A.BOL AS BOLETA,
  COALESCE(FORMAT("$%'.2f", A.TRN_IMP), '$0.00') AS IMP_BOLETA,
  COALESCE(FORMAT("$%'.2f", A.IMP_DESC_BOL), '$0.00') AS IMP_DESC_BOL,
  COALESCE(FORMAT("$%'.2f", A.IMP_RBJ_BOL), '$0.00') AS IMP_RBJ_BOL,
  COALESCE(FORMAT("$%'.2f", A.IMP_TRN_RGL), '$0.00') AS IMP_TRN_RGL,
  A.NUM_CELULAR,
  A.IS_DEV_POS,
  A.VND_CVE AS VENDEDOR,
  A.SKU_AGG,
  A.ORI_AGG,
  B.PLAN_CVE,
  A.SOMS_OMS,
  A.TIP_TRANSA,
  A.DISPOSITIVO,
  A.CANAL,
  B.TIP_PAGO,
  B.MED_ING,
  B.BANCO,
  A.DES_MOT_DEV,
  A.TDA_CVE_REC
FROM POS_TRN AS A
LEFT JOIN TIP_PAG AS B
  ON A.FCH_FCH = B.FCH_FCH
  AND A.TDA_CVE = B.TDA_CVE
  AND A.NUM_TER = B.NUM_TER
  AND A.BOL = B.BOL
ORDER BY 1, 4, 5;

DROP TABLE IF EXISTS CTAS_REV;
DROP TABLE IF EXISTS CTA_TRJ;
DROP TABLE IF EXISTS POS_TRN;
DROP TABLE IF EXISTS TIP_PAG;

